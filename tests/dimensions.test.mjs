import test from 'node:test'
import assert from 'node:assert/strict'
import { harness } from './harness.mjs'

test('Custom dimensions preserve cents through member and account rollups and version their moved cells while approvals stay frozen', async t => {
 const h = await harness(); t.after(() => h.close())
 await h.command('workspace', { name: 'Synthetic dimensions', currency: 'USD', fiscalYearStart: 1, planStart: '2026-01' })
 const department = await h.command('department', { name: 'Sales' })
 const advertising = await h.command('line', { name: 'Advertising', type: 'operating-expense' })
 const events = await h.command('line', { name: 'Events', type: 'operating-expense' })
 const scenario = (await h.get('/api/easel/state')).scenarios[0]
 const region = await h.command('dimension', { name: 'Region' })
 const world = await h.command('dimension-member', { dimension: region.id, name: 'All regions' })
 const domestic = await h.command('dimension-member', { dimension: region.id, name: 'Domestic', parent: world.id })
 const east = await h.command('dimension-member', { dimension: region.id, name: 'East', parent: domestic.id })
 const west = await h.command('dimension-member', { dimension: region.id, name: 'West', parent: domestic.id })
 const international = await h.command('dimension-member', { dimension: region.id, name: 'International', parent: world.id })
 const other = await h.command('dimension', { name: 'Product' })
 await h.command('dimension-member', { id: world.id, dimension: region.id, name: 'All regions', parent: east.id }, h.owner, 400)
 await h.command('schedule', { scenario: scenario.id, name: 'Wrong member', line: advertising.id, department: department.id, dimensions: { [other.id]: east.id }, values: { '2026-01': '1' } }, h.owner, 400)
 const a = await h.command('schedule', { scenario: scenario.id, name: 'Eastern ads', line: advertising.id, department: department.id, dimensions: { [region.id]: east.id }, values: { '2026-01': '10.01', '2026-02': '-0.01' } })
 await h.command('expense', { scenario: scenario.id, name: 'Western events', kind: 'recurring', line: events.id, department: department.id, dimensions: { [region.id]: west.id }, start: '2026-01', amount: '20.02' })
 const operating = await h.command('line-group', { name: 'Operating expense', type: 'operating-expense' })
 const marketing = await h.command('line-group', { name: 'Sales and marketing', type: 'operating-expense', parent: operating.id })
 await h.command('line-hierarchy', { line: advertising.id, parent: marketing.id })
 await h.command('line-hierarchy', { line: events.id, parent: marketing.id })
 const report = () => h.get(`/api/easel/dimension-report/${scenario.id}?dimension=${region.id}`)
 let r = await report()
 const member = (r, id) => r.dimensions[0].members.find(m => m.id === id)
 assert.equal(member(r, east.id).lineTotals[advertising.id]['2026-01'], 1001)
 assert.equal(member(r, domestic.id).amounts['2026-01'], 3003)
 assert.equal(member(r, world.id).amounts['2026-02'], 2001)
 assert.deepEqual(member(r, world.id).lineTotals, r.lineTotals)
 const calculation = (await h.get(`/api/easel/scenario/${scenario.id}`)).calculation
 for (const month of r.months) {
  const expected = Object.values(calculation.lineTotals).reduce((sum, amounts) => sum + (amounts[month] ?? 0), 0)
  for (const group of r.accountHierarchy) assert.equal(group.amounts[month], expected)
  assert.equal(r.amounts[month], expected)
 }
 await h.command('dimension-member', { id: east.id, dimension: region.id, name: 'East coast', parent: international.id })
 r = await report()
 assert.equal(member(r, domestic.id).amounts['2026-01'], 2002)
 assert.equal(member(r, international.id).amounts['2026-01'], 1001)
 const version = (await h.get('/api/easel/activity?action=structure-version'))[0]
 assert.ok(version.detail.changes.some(c => c.kind === 'dimension-member' && c.fields.some(f => f.field === 'parent' && f.before === domestic.id && f.after === international.id)))
 const moved = version.detail.scenarios.find(s => s.id === scenario.id).changedCells
 assert.ok(moved.some(c => c.dimension === region.id && c.member === domestic.id && c.line === advertising.id && c.month === '2026-01' && c.before === 1001 && c.after === null && c.difference === null))
 const shared = await h.command('department', { name: 'Shared services', shared: true })
 const recipient = await h.command('department', { name: 'Operations' })
 for (const [name, id] of [['East shared', east.id], ['West shared', west.id]]) await h.command('expense', { scenario: scenario.id, name, kind: 'one-off', line: advertising.id, department: shared.id, dimensions: { [region.id]: id }, start: '2026-01', amount: '0.01' })
 await h.command('allocation', { scenario: scenario.id, name: 'Half to each department', sourceDepartment: shared.id, basis: 'fixed', targets: [{ department: department.id, percent: '50' }, { department: recipient.id, percent: '50' }] })
 const allocated = await report()
 assert.equal(member(allocated, east.id).amounts['2026-01'], 1002)
 assert.equal(member(allocated, west.id).amounts['2026-01'], 2003)
 assert.equal(allocated.cells.filter(c => c.department === shared.id).reduce((sum, c) => sum + c.amount, 0), 0)
 assert.equal(allocated.cells.filter(c => c.department === recipient.id).reduce((sum, c) => sum + c.amount, 0), 1)
 assert.equal(allocated.cells.filter(c => c.month === '2026-01').reduce((sum, c) => sum + c.amount, 0), allocated.amounts['2026-01'])
 const planner = await h.person('planner@example.test', 'contributor', [department.id])
 await h.command('dimension', { name: 'Unauthorized' }, planner, 403)
 await h.command('dimension-member-delete', { id: east.id }, h.owner, 409)
 await h.command('dimension-delete', { id: region.id }, h.owner, 409)
 const approved = await h.command('approve-budget', { scenario: scenario.id, revision: (await h.get(`/api/easel/scenario/${scenario.id}`)).scenario.revision })
 const frozen = await report()
 const snapshots = (await h.get('/api/easel/state')).snapshots
 const snapshot = await h.get(`/api/easel/snapshot/${snapshots.find(s => s.kind === 'approval').id}`)
 assert.ok(snapshot.body.structure['dimension-member'].some(m => m.id === east.id && m.name === 'East coast'))
 const forecastInput = (await h.get(`/api/easel/scenario/${approved.forecast.id}`)).inputs.schedule.find(row => row.originId === a.originId)
 await h.command('input-dimensions', { id: forecastInput.id, kind: 'schedule', scenario: approved.forecast.id, revision: (await h.get(`/api/easel/scenario/${approved.forecast.id}`)).scenario.revision, dimensions: { [region.id]: west.id } })
 const tagVersion = (await h.get('/api/easel/activity?action=structure-version'))[0]
 assert.ok(tagVersion.detail.scenarios.find(s => s.id === approved.forecast.id).changedCells.some(c => c.dimension === region.id && c.member === east.id && c.before === 1001 && c.after === null))
 await h.command('dimension-member', { id: east.id, dimension: region.id, name: 'Renamed after approval', parent: domestic.id })
 await h.command('line-hierarchy', { line: events.id, parent: operating.id })
 assert.deepEqual(await report(), frozen)
 assert.deepEqual(await h.get(`/api/easel/snapshot/${snapshot.id}`), snapshot)
})

test('Source class, department and tracking rules preserve actual cuts and block only dependent line cells after a rule changes', async t => {
 const h = await harness(); t.after(() => h.close())
 await h.command('workspace', { name: 'Ridgeline source dimensions', currency: 'USD', fiscalYearStart: 1, planStart: '2026-01' })
 const dept = await h.command('department', { name: 'Commercial' })
 const ads = await h.command('line', { name: 'Advertising', type: 'operating-expense' })
 const events = await h.command('line', { name: 'Events', type: 'operating-expense' })
 const region = await h.command('dimension', { name: 'Region' })
 const total = await h.command('dimension-member', { dimension: region.id, name: 'Domestic' })
 const east = await h.command('dimension-member', { dimension: region.id, name: 'East', parent: total.id })
 const west = await h.command('dimension-member', { dimension: region.id, name: 'West', parent: total.id })
 const channel = await h.command('dimension', { name: 'Channel' })
 const direct = await h.command('dimension-member', { dimension: channel.id, name: 'Direct' })
 const business = await h.command('dimension', { name: 'Business unit' })
 const sales = await h.command('dimension-member', { dimension: business.id, name: 'Sales' })
 await h.command('account-map', { account: '500', target: ads.id }); await h.command('account-map', { account: '510', target: events.id })
 await h.command('department-map', { source: 'Commercial', department: dept.id })
 const map = (dimension, member, sourceKind, source, match = 'exact') => h.command('dimension-map', { dimension, member, sourceKind, source, match })
 const eastRule = await map(region.id, east.id, 'class', 'East-1')
 await map(region.id, west.id, 'class', 'West-', 'prefix')
 await map(channel.id, direct.id, 'tracking-option', 'Direct')
 await map(business.id, sales.id, 'department', 'Commercial')
 const file = { filename: 'synthetic-easel-1.csv', dateFormat: 'YYYY-MM-DD', columns: { date: 'Date', account: 'Account', department: 'Department', amount: 'Amount', class: 'Class', trackingOption: 'Tracking option' }, csv: 'Date,Account,Department,Amount,Class,Tracking option\n2026-01-10,500,Commercial,10.01,East-1,Direct\n2026-01-11,500,Commercial,20.02,West-1,Direct\n2026-01-12,510,Commercial,30.03,West-2,Direct\n' }
 const p = await h.kit('actuals', 'preview', file)
 assert.deepEqual(p.dimensionExceptions, [])
 await h.kit('actuals', 'commit', { ...file, fingerprint: p.fingerprint })
 let report = await h.get(`/api/easel/dimension-report/actuals?dimension=${region.id}`)
 assert.equal(report.dimensions[0].members.find(m => m.id === east.id).lineTotals[ads.id]['2026-01'], 1001)
 assert.equal(report.dimensions[0].members.find(m => m.id === west.id).lineTotals[ads.id]['2026-01'], 2002)
 assert.equal(report.dimensions[0].members.find(m => m.id === total.id).amounts['2026-01'], 6006)
 const tracked = await h.get(`/api/easel/dimension-report/actuals?dimension=${channel.id}`)
 assert.equal(tracked.dimensions[0].members.find(m => m.id === direct.id).amounts['2026-01'], 6006)
 await h.command('dimension-map', { id: eastRule.id, dimension: region.id, member: east.id, sourceKind: 'class', source: 'Renamed class' })
 report = await h.get(`/api/easel/dimension-report/actuals?dimension=${region.id}`)
 assert.equal(report.lineTotals[ads.id]['2026-01'], null)
 assert.equal(report.lineTotals[events.id]['2026-01'], 3003)
 assert.equal(report.blocked.length, 1)
 assert.equal(report.dimensions[0].members.find(m => m.id === total.id).amounts['2026-01'], null)
 const independent = await h.get(`/api/easel/dimension-report/actuals?dimension=${channel.id}`)
 assert.equal(independent.lineTotals[events.id]['2026-01'], 3003)
 await h.command('dimension-map', { id: eastRule.id, dimension: region.id, member: east.id, sourceKind: 'class', source: 'East-1' })
 const conflicting = await map(region.id, west.id, 'class', 'East-', 'prefix')
 const second = { ...file, filename: 'synthetic-easel-2.csv', csv: file.csv.replaceAll('2026-01', '2026-02') }
 const conflict = await h.kit('actuals', 'preview', second)
 assert.ok(conflict.dimensionExceptions.some(e => e.reason === 'Conflicting dimension rules'))
 await h.kit('actuals', 'commit', { ...second, fingerprint: conflict.fingerprint }, h.owner, 409)
 await h.command('dimension-map-delete', { id: conflicting.id })
 const workbook = await h.mf.dispatchFetch(`${h.origin}/api/easel/dimension-report/actuals/document.xlsx?dimension=${region.id}`, { headers: { cookie: h.owner } })
 assert.equal(workbook.status, 200)
 const person = await h.person('east@example.test', 'contributor', [dept.id], false)
 await h.command('member', { email: 'east@example.test', name: 'East planner', role: 'contributor', departments: [dept.id], dimensionMembers: { [region.id]: [east.id] } })
 const scenario = (await h.get('/api/easel/state')).scenarios[0]
 await h.command('request-submissions', { scenario: scenario.id, departments: [dept.id] })
 const allowed = await h.command('schedule', { scenario: scenario.id, name: 'East plan', line: ads.id, department: dept.id, dimensions: { [region.id]: east.id }, values: { '2026-01': '1' } }, person)
 await h.command('schedule', { scenario: scenario.id, name: 'West plan', line: ads.id, department: dept.id, dimensions: { [region.id]: west.id }, values: { '2026-01': '1' } }, person, 403)
 const request = { scenario: scenario.id, revision: (await h.get(`/api/easel/scenario/${scenario.id}`)).scenario.revision, changes: [{ schedule: allowed.id, month: '2026-01', value: '2' }] }
 const preview = await h.command('grid-preview', request, person)
 assert.deepEqual(preview.refused, [])
 await h.command('member', { email: 'east@example.test', name: 'East planner', role: 'contributor', departments: [dept.id], dimensionMembers: { [region.id]: [west.id] } })
 await h.command('grid-save', { ...request, fingerprint: preview.fingerprint }, person, 400)
 assert.equal((await h.get(`/api/easel/scenario/${scenario.id}`)).inputs.schedule.find(r => r.id === allowed.id).values['2026-01'], 100)
})
