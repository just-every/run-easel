import test from 'node:test'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import JSZip from 'jszip'
import { harness } from './harness.mjs'
import { dashboardFixture } from './dashboard-fixture.mjs'
import { readWorkbook, proveFormulas } from './spreadsheet-proof.mjs'

test('REPORT-002 configurable dashboards retain personal layouts, exact aggregate metrics and live audience authority', async t => {
 const h = await harness(); t.after(() => h.close())
 const f = await dashboardFixture(h.command, path => h.get(`/api/easel/${path}`))
 const board = await h.person('board@example.test', 'viewer')
 const sales = await h.person('sales@example.test', 'contributor', [f.sales.id])
 const delivery = await h.person('delivery@example.test', 'contributor', [f.delivery.id])
 const otherFinance = await h.person('other@example.test', 'finance')
 for (const who of [board, sales, delivery]) await h.command('dashboard-save', f.body, who, 403)
 const d = await h.command('dashboard-save', f.body)
 const path = `/api/easel/dashboards/${d.id}`, read = (who = h.owner) => h.get(path, who)
 let own = await read(), shared = await read(board)
 assert.deepEqual(shared.rows, own.rows)
 assert.equal(shared.rows.length, 12)
 for (const [i, row] of shared.rows.entries()) {
  assert.equal(row.arr, 12000000, 'only customer and seat revenue, even when nonrecurring revenue shares their line')
  assert.equal(row.revenue, 1500000); assert.equal(row.grossMargin, 1200000); assert.equal(row.headcount, 2)
  assert.equal(row.burn, 550000); assert.equal(row.closingCash, 10000000 - (i + 1) * 550000)
  assert.equal(row.runway, Math.round(row.closingCash * 100 / 550000))
 }
 assert.doesNotMatch(JSON.stringify(shared), /Private Salary Person|Private compensation|annualSalary|sources|originId/)
 assert.ok((await h.get('/api/easel/dashboards', board)).some(row => row.id === d.id))
 for (const who of [sales, delivery]) await h.get(path, who, 404)
 const personal = [...d.widgets].reverse().map(w => ({ ...w, display: 'table' }))
 await h.command('dashboard-layout', { dashboard: d.id, revision: 0, definitionRevision: d.revision, widgets: personal }, board)
 shared = await read(board)
 assert.deepEqual(shared.widgets, personal); assert.deepEqual((await read()).widgets, d.widgets)
 const ownLayoutAudit = await h.db.prepare("SELECT detail FROM e_activity WHERE action='record-changed' AND json_extract(detail,'$.kind')='dashboard-layout'").all()
 assert.ok(ownLayoutAudit.results.length)
 assert.ok(ownLayoutAudit.results.every(row => !JSON.parse(row.detail).after.widgets), 'Personal arrangements never enter audit payloads')
 await h.command('dashboard-layout', { dashboard: d.id, revision: 0, definitionRevision: d.revision, widgets: d.widgets }, board, 409)
 await h.command('dashboard-layout', { dashboard: d.id, revision: 1, definitionRevision: 0, widgets: d.widgets }, board, 409)
 await h.command('dashboard-layout', { dashboard: d.id, revision: 1, definitionRevision: d.revision, widgets: [{ metric: 'arr', display: 'tile' }] }, board, 400)
 assert.deepEqual((await read(board)).widgets, personal)
 const download = async (suffix, who = board) => h.mf.dispatchFetch(h.origin + path + suffix, { headers: { cookie: who } })
 const excel = await download('/document.xlsx'); assert.equal(excel.status, 200)
 const book = await readWorkbook(await excel.arrayBuffer()); proveFormulas(book)
 assert.equal(book.getWorksheet('Dashboard').getCell('G3').result, 12000000)
 assert.doesNotMatch(JSON.stringify(book.model), /Private Salary Person|Private compensation|annualSalary/)
 await h.command('dashboard-save', { ...f.body, id: d.id, revision: d.revision - 1 }, h.owner, 409)
 await h.command('dashboard-save', { ...f.body, id: d.id, revision: d.revision }, otherFinance, 404)
 const privateBoard = await h.command('dashboard-save', { ...f.body, name: 'Private dashboard name', audience: 'private' }, otherFinance)
 await h.command('dashboard-layout', { dashboard: privateBoard.id, revision: 0, definitionRevision: privateBoard.revision, widgets: privateBoard.widgets }, otherFinance)
 assert.ok(!(await h.get('/api/easel/dashboards')).some(v => v.id === privateBoard.id))
 // Open export repeats dashboard/layout authority and keeps every visible digest.
 const archiveResponse = await h.mf.dispatchFetch(h.origin + '/api/easel/export', { headers: { cookie: h.owner } })
 const archive = await JSZip.loadAsync(await archiveResponse.arrayBuffer())
 const manifest = JSON.parse(await archive.file('manifest.json').async('string'))
 for (const file of manifest.files) assert.equal(createHash('sha256').update(await archive.file(file.path).async('uint8array')).digest('hex'), file.sha256)
 for (const file of ['model.json', 'tables/e_records.csv', 'tables/e_activity.csv']) assert.doesNotMatch(await archive.file(file).async('string'), new RegExp(`${privateBoard.id}|Private dashboard name`))
 const exported = JSON.parse(await archive.file('model.json').async('string'))
 assert.ok(!exported.records.some(r => r.kind === 'dashboard-layout'), 'another reader’s layout is private')
 let updated = await h.command('dashboard-save', { ...f.body, id: d.id, revision: d.revision, audience: 'department', department: f.sales.id })
 assert.deepEqual((await read(sales)).rows.map(r => r.arr), Array(12).fill(12000000))
 const scoped = await read(sales)
 assert.ok(scoped.rows.every(r => r.headcount === 1 && r.burn === null && r.runway === null && r.closingCash === null))
 for (const who of [board, delivery]) { await h.get(path, who, 404); assert.equal((await download('/document.xlsx', who)).status, 404) }
 await h.command('dashboard-layout', { dashboard: d.id, revision: 1, definitionRevision: updated.revision, widgets: personal }, board, 404)
 await h.command('member', { email: 'sales@example.test', name: 'sales', role: 'contributor', departments: [f.delivery.id] })
 await h.get(path, sales, 404)
 updated = await h.command('dashboard-save', { ...f.body, id: d.id, revision: updated.revision, audience: 'leadership' })
 assert.equal((await read(otherFinance)).dashboard.id, d.id)
 await h.get(path, board, 404)
 const sandbox = await h.command('branch', { from: f.budget.id, name: 'Private sandbox', privateSandbox: true })
 await h.command('dashboard-save', { ...f.body, scenario: sandbox.id }, h.owner, 409)
 // Frozen dashboard metrics remain captured when the working source changes.
 const approved = await h.command('approve-budget', { scenario: f.budget.id, revision: (await h.get(`/api/easel/scenario/${f.budget.id}`)).scenario.revision })
 const frozen = await read()
 const forecast = await h.command('dashboard-save', { ...f.body, name: 'Forecast', scenario: approved.forecast.id })
 const actuals = { filename: 'closed.csv', csv: 'Date,Account,Department,Amount\n2026-01-31,400,Sales,-10000\n', columns: { date: 'Date', account: 'Account', department: 'Department', amount: 'Amount' }, dateFormat: 'YYYY-MM-DD', amountMode: 'debit-positive' }
 await h.command('account-map', { account: '400', target: f.revenue.id })
 await h.command('department-map', { source: 'Sales', department: f.sales.id })
 const preview = await h.kit('actuals', 'preview', actuals)
 await h.kit('actuals', 'commit', { ...actuals, fingerprint: preview.fingerprint })
 await h.command('close-month', { scenario: approved.forecast.id, month: '2026-01' })
 const forecastView = await h.get(`/api/easel/dashboards/${forecast.id}`)
 assert.equal(forecastView.rows[0].arr, null, 'ledger actuals never silently become subscription ARR')
 assert.equal(forecastView.rows[0].revenue, 1000000)
 assert.deepEqual((await read()).rows, frozen.rows)
 await h.command('account-map', { account: '400', target: 'excluded' })
 const missing = await h.get(`/api/easel/dashboards/${forecast.id}`)
 assert.equal(missing.rows[0].revenue, null); assert.equal(missing.rows[0].grossMargin, null)
 assert.ok(missing.rows.every(row => row.closingCash === null && row.runway === null && row.burn === null))
 await h.command('account-map', { account: '400', target: f.revenue.id })
 await h.command('department-map', { source: 'Sales', department: '' })
 await h.get(`/api/easel/dashboards/${forecast.id}`, h.owner, 409)
 await h.command('department-map', { source: 'Sales', department: f.sales.id })
 const bulk = { ...actuals, filename: 'late-adjustments.csv', columns: { ...actuals.columns, reference: 'Reference' }, csv: 'Date,Account,Department,Amount,Reference\n' + Array.from({ length: 201 }, (_, i) => `2026-01-31,400,Sales,-1,adjustment-${i}`).join('\n') }
 const bp = await h.kit('actuals', 'preview', bulk)
 let importing = await h.kit('actuals', 'commit', { ...bulk, fingerprint: bp.fingerprint })
 assert.equal(importing.batch.status, 'importing')
 const incomplete = await h.get(`/api/easel/dashboards/${forecast.id}`)
 assert.ok(incomplete.blocked)
 assert.ok(incomplete.rows.every(row => row.arr === null && row.revenue === null && row.burn === null && row.headcount === 2))
 while (importing.batch.status === 'importing') importing = await h.kit('actuals', 'resume', { id: importing.batch.id })
 assert.equal(importing.batch.status, 'accepted')
 assert.equal((await h.get(`/api/easel/dashboards/${forecast.id}`)).blocked, null)
 // A personal layout reset on a new shared definition never mutates its saved row.
 const boardAgain = await h.command('dashboard-save', { ...f.body, id: forecast.id, revision: forecast.revision })
 await h.command('dashboard-layout', { dashboard: forecast.id, revision: 0, definitionRevision: boardAgain.revision, widgets: personal }, board)
 const redefined = await h.command('dashboard-save', { ...f.body, id: forecast.id, revision: boardAgain.revision, widgets: [{ metric: 'revenue', display: 'table' }] })
 assert.deepEqual((await h.get(`/api/easel/dashboards/${forecast.id}`, board)).widgets, redefined.widgets)
 await h.command('member', { email: 'board@example.test', name: 'board', role: 'viewer', active: false })
 await h.get(`/api/easel/dashboards/${forecast.id}`, board, 403)
 await h.command('dashboard-delete', { id: d.id, revision: updated.revision - 1 }, h.owner, 409)
 await h.command('dashboard-delete', { id: d.id, revision: updated.revision })
 await h.get(path, h.owner, 404)
 await h.get(path, otherFinance, 404)
})
