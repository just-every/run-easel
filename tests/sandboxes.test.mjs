import test from 'node:test'
import assert from 'node:assert/strict'
import JSZip from 'jszip'
import { harness } from './harness.mjs'
import { readWorkbook, proveFormulas } from './spreadsheet-proof.mjs'

test('CYCLE-004 private sandboxes, live read/edit shares, official cases and exact scoped proposals through HTTP', async t => {
 const h = await harness(); t.after(() => h.close())
 await h.command('workspace', { name: 'Raleigh Services', currency: 'USD', fiscalYearStart: 1, planStart: '2026-01' })
 const sales = await h.command('department', { name: 'Sales' }), eng = await h.command('department', { name: 'Engineering' })
 const revenue = await h.command('line', { name: 'Contracts', type: 'revenue' }), pay = await h.command('line', { name: 'Payroll', type: 'operating-expense', payroll: true })
 const budget = (await h.get('/api/easel/state')).scenarios[0]
 const model = { scenario: budget.id, name: 'Retainers', line: revenue.id, department: sales.id, kind: 'volume', start: '2026-01', startVolume: '10', rate: '1000' }
 await h.command('revenue', model)
 await h.command('position', { scenario: budget.id, title: 'Engineer', holder: 'Confidential Person', department: eng.id, line: pay.id, start: '2026-01', annualSalary: '193721.23', onCostPercent: '12' })
 const author = await h.person('sales@example.test', 'contributor', [sales.id])
 const other = await h.person('engineering@example.test', 'contributor', [eng.id])
 const viewer = await h.person('board@example.test', 'viewer')
 const read = (id, who = author, status = 200) => h.get(`/api/easel/scenario/${id}`, who, status)
 const edit = (sc, who, status = 200, extra = {}) => h.command('revenue', { ...model, scenario: sc.id, name: 'Private expansion', startVolume: '12', ...extra }, who, status)
 await h.command('sandbox-create', { from: budget.id, name: 'Viewer draft' }, viewer, 403)
 const sandbox = await h.command('sandbox-create', { from: budget.id, name: 'Private expansion case' }, author)
 const original = await read(budget.id)
 for (const who of [other, viewer, h.owner]) {
  await read(sandbox.id, who, 404)
  assert.equal((await h.get('/api/easel/state', who)).scenarios.some(sc => sc.id === sandbox.id), false)
  await h.get(`/api/easel/compare?a=${budget.id}&b=${sandbox.id}`, who, 404)
  for (const suffix of ['document.csv', 'document.xlsx']) await h.get(`/api/easel/scenario/${sandbox.id}/${suffix}`, who, 404)
  await h.get(`/api/easel/compare.xlsx?a=${budget.id}&b=${sandbox.id}`, who, 404)
  await edit(sandbox, who, 404)
 }
 await h.command('branch', { from: sandbox.id, name: 'Leak branch' }, h.owner, 404)
 await h.command('reforecast-save', { from: sandbox.id, name: 'Leak freeze', revision: 1 }, h.owner, 404)
 await h.command('scenario-adopt', { from: sandbox.id, into: budget.id, revision: original.scenario.revision }, h.owner, 404)
 assert.deepEqual(await read(budget.id), original)
 const secret = await edit(sandbox, author)
 await edit(sandbox, author, 403, { department: eng.id })
 let view = await read(sandbox.id)
 assert.equal(view.calculation.lineTotals[revenue.id]['2026-01'], 2200000)
 assert.doesNotMatch(JSON.stringify(view), /Confidential Person|19372123/)
 const share = async (email, mode, who = author, status = 200, revision) => h.command('scenario-share', { scenario: sandbox.id, revision: revision ?? (await read(sandbox.id)).scenario.revision, email, mode }, who, status)
 await share('owner@example.test', 'read')
 await read(sandbox.id, h.owner)
 await edit(sandbox, h.owner, 403)
 await share('owner@example.test', 'remove')
 await read(sandbox.id, h.owner, 404)
 await share('board@example.test', 'edit', author, 403)
 await share('board@example.test', 'read')
 await share('engineering@example.test', 'edit')
 await share('board@example.test', 'read', author, 409, 1)
 view = await read(sandbox.id, viewer)
 assert.equal(view.calculation.lineTotals[revenue.id]['2026-01'], 2200000)
 assert.deepEqual(view.inputs.revenue, []); assert.deepEqual(view.inputs.position, [])
 const cmp = await h.get(`/api/easel/compare?a=${budget.id}&b=${sandbox.id}`, viewer)
 assert.equal(cmp.changedCells.find(c => c.line === revenue.id).difference, 1200000)
 assert.doesNotMatch(JSON.stringify(cmp), /Confidential Person|Private expansion"/)
 await edit(sandbox, viewer, 403)
 await edit(sandbox, other, 403) // edit share keeps department restrictions
 await edit(sandbox, other, 200, { name: 'Engineering contracts', department: eng.id, startVolume: '1' })
 // Restore the sandbox to changes its creator can submit.
 const otherInput = (await read(sandbox.id, other)).inputs.revenue.find(r => r.department === eng.id)
 await h.command('input-delete', { kind: 'revenue', id: otherInput.id }, other)
 await share('engineering@example.test', 'read')
 await edit(sandbox, other, 403, { department: eng.id })
 const bookResponse = await h.mf.dispatchFetch(h.origin + `/api/easel/scenario/${sandbox.id}/document.xlsx`, { headers: { cookie: viewer } })
 assert.equal(bookResponse.status, 200)
 const book = await readWorkbook(await bookResponse.arrayBuffer()); proveFormulas(book)
 assert.doesNotMatch(JSON.stringify(book.worksheets.map(s => s.getSheetValues())), /Confidential Person|19372123/)
 await h.command('comment', { scenario: sandbox.id, department: sales.id, text: 'Private hiring discussion' }, author)
 assert.doesNotMatch(JSON.stringify(await h.get('/api/easel/state')), /Private expansion case|Private hiring discussion/)
 // Finance Activity and its CSV/Excel projection must not leak private definitions.
 await h.command('line', { ...revenue, name: 'Client contracts' })
 for (const path of ['/api/easel/activity', '/api/easel/activity.csv']) {
  const result = await h.get(path)
  assert.doesNotMatch(JSON.stringify(result), new RegExp(`${sandbox.id}|Private expansion case|Private hiring discussion|${secret.id}`))
 }
 const zipResponse = await h.mf.dispatchFetch(h.origin + '/api/easel/export', { headers: { cookie: h.owner } })
 assert.equal(zipResponse.status, 200)
 const zip = await JSZip.loadAsync(await zipResponse.arrayBuffer())
 const manifest = JSON.parse(await zip.file('manifest.json').async('string'))
 for (const file of manifest.files) {
  const bytes = await zip.file(file.path).async('uint8array')
  assert.equal(bytes.length, file.size)
  const digest = await crypto.subtle.digest('SHA-256', bytes)
  assert.equal(Buffer.from(digest).toString('hex'), file.sha256)
 }
 for (const entry of Object.values(zip.files).filter(f => !f.dir && /\.json$|\.csv$/.test(f.name))) assert.doesNotMatch(await entry.async('string'), new RegExp(`${sandbox.id}|Private expansion case|Private hiring discussion|${secret.id}`), entry.name)
 const beforeSubmit = await read(sandbox.id)
 await h.command('member', { email: 'sales@example.test', name: 'sales', role: 'contributor', departments: [eng.id] })
 await h.command('sandbox-submit', { scenario: sandbox.id, revision: beforeSubmit.scenario.revision, request: 'Scope was removed' }, author, 403)
 await h.command('member', { email: 'sales@example.test', name: 'sales', role: 'contributor', departments: [sales.id] })
 const proposal = await h.command('sandbox-submit', { scenario: sandbox.id, revision: beforeSubmit.scenario.revision, request: 'Expand Sales only' }, author)
 assert.equal(proposal.kind, 'proposal'); assert.equal(proposal.proposalStatus, 'submitted')
 assert.equal(proposal.branchedFrom.revision, original.scenario.revision)
 assert.deepEqual(await read(sandbox.id), beforeSubmit, 'submission preserves the private original')
 await read(proposal.id, h.owner)
 await read(proposal.id, viewer, 404)
 await h.command('proposal-promote', { id: proposal.id, revision: proposal.revision })
 assert.equal((await read(budget.id)).calculation.lineTotals[revenue.id]['2026-01'], 2200000)
 await h.command('sandbox-submit', { scenario: sandbox.id, revision: beforeSubmit.scenario.revision, request: 'Stale source' }, author, 409)
 const official = await h.command('scenario-official', { scenario: budget.id, revision: (await read(budget.id)).scenario.revision, official: 'budget' })
 assert.equal(official.official, 'budget')
 await h.command('scenario-official', { scenario: sandbox.id, revision: beforeSubmit.scenario.revision, official: 'board-case' }, author, 403)
 await h.command('scenario-official', { scenario: budget.id, revision: official.revision, official: 'forecast' }, author, 403)
 const boardCase = await h.command('branch', { from: budget.id, name: 'Board case' })
 for (const [sc, designation] of [[boardCase, 'board-case'], [budget, 'forecast']]) {
  const prior = await read(sc.id, viewer)
  await h.command('scenario-official', { scenario: sc.id, revision: prior.scenario.revision, official: designation })
  const after = await read(sc.id, viewer)
  assert.equal(after.scenario.official, designation)
  assert.deepEqual(after.calculation, prior.calculation)
 }
 // Revocation and current membership end all doors immediately.
 await share('board@example.test', 'remove')
 await read(sandbox.id, viewer, 404)
 await h.command('member', { email: 'engineering@example.test', name: 'engineering', role: 'contributor', departments: [eng.id], active: false })
 await read(sandbox.id, other, 403)
 const privateFinance = await h.command('sandbox-create', { from: budget.id, name: 'Finance private case' })
 await read(privateFinance.id, author, 404)
 await h.command('scenario-share', { scenario: privateFinance.id, revision: privateFinance.revision, email: 'sales@example.test', mode: 'edit' })
 await read(privateFinance.id, author)
})
