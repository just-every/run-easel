import assert from 'node:assert/strict'
import JSZip from 'jszip'
import { readWorkbook, proveFormulas } from './spreadsheet-proof.mjs'
import { insertLinked, refreshLinked, linkedItems } from '../public/office/adapter.mjs'
import { createOfficeHost } from './office-host.mjs'

// Called from the existing saved-report test file: real HTTP -> production
// Office adapter -> the explicitly required Office.js test host -> .pptx bytes.
export async function officeReportFlow(h) {
 await h.command('workspace', { name: 'Harbor quarterly reporting', planStart: '2026-01', currency: 'USD' })
 const ops = await h.command('department', { name: 'Operations' })
 const sales = await h.command('department', { name: 'Sales' })
 const revenue = await h.command('line', { name: 'Service revenue', type: 'revenue' })
 const payroll = await h.command('line', { name: 'Payroll', type: 'operating-expense', payroll: true })
 const scenario = (await h.get('/api/easel/state')).scenarios[0].id
 const schedule = await h.command('schedule', { scenario, name: 'Delivery revenue', department: ops.id, line: revenue.id, values: { '2026-01': '1234.56' } })
 await h.command('schedule', { scenario, name: 'Sales revenue', department: sales.id, line: revenue.id, values: { '2026-01': '9876.54' } })
 await h.command('position', { scenario, title: 'Private compensation role', holder: 'Private compensation person', department: ops.id, line: payroll.id, start: '2026-01', annualSalary: '120000' })
 const report = await h.command('report-save', { name: 'Leadership operating report', scenario, department: '', audience: 'board', report: { row: 'department', period: 'month', through: '2026-03', lines: [revenue.id, payroll.id], comparisons: [], highlightBps: 1000 } })
 const board = await h.person('office-board@example.test', 'viewer')
 const query = binding => new URLSearchParams(Object.entries(binding).filter(([, value]) => typeof value === 'string')).toString()
 const read = (binding, person = h.owner, status = 200) => h.get(`/api/easel/dashboards/${report.id}/office?${query(binding)}`, person, status)
 const binding = { report: report.id, source: scenario, through: '2026-03', period: '2026-01', kind: 'table', metric: 'budget', row: 'all' }
 const table = await read(binding, board)
 assert.equal(table.table.find(r => r[0] === 'Operations')[1], '$11,234.56')
 assert.doesNotMatch(JSON.stringify(table), /Private compensation/)
 const host = createOfficeHost('PowerPoint')
 await insertLinked(host, table)
 await insertLinked(host, await read({ ...binding, kind: 'number', row: ops.id }, board))
 const before = await host.pptx()
 const beforeZip = await JSZip.loadAsync(before)
 assert.match(await beforeZip.file('ppt/slides/slide1.xml').async('string'), /11,234\.56/)
 const originalLinks = structuredClone(linkedItems(host))
 await h.command('schedule', { scenario, id: schedule.id, name: 'Delivery revenue', department: ops.id, line: revenue.id, values: { '2026-01': '2234.56' } })
 assert.equal((await refreshLinked(host, b => read(b, board))).updated, 2)
 assert.deepEqual(linkedItems(host), originalLinks, 'refresh preserves target identifiers and bound source selectors')
 const zip = await JSZip.loadAsync(await host.pptx())
 const slide = await zip.file('ppt/slides/slide1.xml').async('string')
 assert.match(slide, /12,234\.56/); assert.doesNotMatch(slide, /11,234\.56/)
 assert.match(slide, /<a:tbl[ >]/, 'the linked table is an actual PowerPoint table')
 const reopened = host.reopen()
 assert.deepEqual(linkedItems(reopened), linkedItems(host))
 assert.equal((await refreshLinked(reopened, b => read(b, board))).updated, 2)
 const duplicate = host.reopen(); duplicate.duplicateTarget(linkedItems(duplicate)[0])
 await assert.rejects(refreshLinked(duplicate, b => read(b, board)), /duplicated/)
 const deleted = host.reopen(); deleted.deleteTarget(linkedItems(deleted)[0])
 await assert.rejects(refreshLinked(deleted, b => read(b, board)), /deleted/)
 const word = createOfficeHost('Word')
 await insertLinked(word, await read(binding, board))
 await insertLinked(word, await read({ ...binding, kind: 'number', row: ops.id }, board))
 const wordLinks = structuredClone(linkedItems(word))
 await h.command('schedule', { scenario, id: schedule.id, name: 'Delivery revenue', department: ops.id, line: revenue.id, values: { '2026-01': '3234.56' } })
 await refreshLinked(word, b => read(b, board))
 const document = (await JSZip.loadAsync(await word.docx())).file('word/document.xml')
 assert.match(await document.async('string'), /13,234\.56/)
 assert.match(await document.async('string'), /<w:tbl>/)
 assert.deepEqual(linkedItems(word), wordLinks)
 const workbook = await h.mf.dispatchFetch(`${h.origin}/api/easel/dashboards/${report.id}/office.xlsx?${query(binding)}`, { headers: { cookie: board } })
 assert.equal(workbook.status, 200)
 const book = await readWorkbook(await workbook.arrayBuffer()); proveFormulas(book)
 assert.doesNotMatch(JSON.stringify(book.worksheets.map(s => s.getSheetValues())), /Private compensation/)
 const chart = await read({ ...binding, kind: 'chart', metric: 'actual' }, board)
 assert.ok(chart.chart.values.every(v => v === null), 'missing actuals remain unavailable, never plotted as observed zeroes')
 await read({ ...binding, period: '2030-01' }, board, 409)
 await read({ ...binding, source: 'synthetic-easel-1' }, board, 409)
 await read({ ...binding, kind: 'number', row: 'synthetic-easel-2' }, board, 409)
 const unauthorized = await h.person('office-outsider@example.test', 'contributor', [sales.id])
 await read(binding, unauthorized, 404)
 await h.command('member', { email: 'office-board@example.test', name: 'Board', role: 'contributor', departments: [sales.id] })
 const unchanged = await host.pptx()
 await assert.rejects(refreshLinked(host, b => read(b, board)), /404|not found/i)
 assert.deepEqual(await host.pptx(), unchanged, 'revoked audience refuses refresh before any document write')
 const manifests = await h.send('/api/office/manifest/PowerPoint')
 assert.equal(manifests.status, 200)
 assert.match(manifests.text, /Presentation/); assert.match(manifests.text, /PowerPointApi/)
 assert.doesNotMatch(manifests.text, /token|secret|owner@example/)
}
