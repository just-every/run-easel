import test from 'node:test'
import assert from 'node:assert/strict'
import { harness } from './harness.mjs'
import { readWorkbook, proveFormulas } from './spreadsheet-proof.mjs'

test('FIN-004 capex, category lives, existing assets and disposals reach exact book values, profit, cash and frozen exports', async t => {
 const h = await harness(); t.after(() => h.close())
 await h.command('workspace', { name:'Harbour Analytics', currency:'USD', fiscalYearStart:1, planStart:'2026-01' })
 const dept = await h.command('department', {name:'Engineering'})
 const line = await h.command('line', {name:'Depreciation and disposals',type:'operating-expense',nonCash:true})
 const other = await h.command('line', {name:'Office costs',type:'operating-expense'})
 const salesDept = await h.command('department',{name:'Sales'})
 const sales = await h.person('sales@example.test','contributor',[salesDept.id])
 const board = await h.person('board@example.test','viewer')
 const budget = (await h.get('/api/easel/state')).scenarios[0]
 const category = await h.command('asset-category',{scenario:budget.id,name:'Equipment',usefulLifeMonths:60})
 const base = {scenario:budget.id,category:category.originId,department:dept.id,line:line.id,kind:'purchase',name:'Production equipment',cost:'120000',start:'2026-01'}
 const asset = await h.command('asset',base)
 const read = async id => h.get(`/api/easel/scenario/${id ?? budget.id}`)
 let view = await read()
 assert.equal(view.calculation.assets[0].depreciation,200000)
 assert.equal(view.calculation.assets[0].closingBookValue,11800000)
 assert.equal(view.calculation.profit[0].profit,-200000)
 assert.equal(view.calculation.cash[0].payments,12000000,'Capex only: depreciation is non-cash')
 await h.command('asset',{...base,id:asset.id,paymentMonth:'2026-03'})
 view = await read()
 assert.equal(view.calculation.cash[0].payments,0)
 assert.equal(view.calculation.cash[2].payments,12000000)
 await h.command('asset',{...base,id:asset.id,paymentMonth:'2026-03',disposalMonth:'2026-04',disposalProceeds:'100000'})
 view = await read()
 const disposal = view.calculation.assets.find(a=>a.month==='2026-04')
 assert.equal(disposal.openingBookValue,11400000)
 assert.equal(disposal.depreciation,0)
 assert.equal(disposal.disposalBookValue,11400000)
 assert.equal(disposal.closingBookValue,0)
 assert.equal(view.calculation.profit[3].profit,-1400000)
 assert.equal(view.calculation.cash[3].collections,10000000)
 assert.equal(view.calculation.cash[3].payments,0)
 assert.equal(view.calculation.assets.find(a=>a.month==='2026-05').closingBookValue,0)
 const existing = await h.command('asset',{...base,name:'Existing laptop',kind:'existing',cost:'1000.01',openingAccumulated:'400',remainingLifeMonths:3})
 view = await read()
 assert.deepEqual(view.calculation.assets.filter(a=>a.originId===existing.originId).slice(0,4).map(a=>[a.depreciation,a.closingBookValue,a.capex]),[[20000,40001,0],[20000,20001,0],[20001,0,0],[0,0,0]])
 await h.command('input-delete',{kind:'asset-category',id:category.id},h.owner,409)
 await h.command('asset',{...base,category:'not-a-category'},h.owner,404)
 await h.command('asset',{...base,line:other.id},h.owner,400)
 await h.command('asset',{...base,cost:'-1'},h.owner,400)
 await h.command('asset-category',{scenario:budget.id,name:'Private category',usefulLifeMonths:12},sales,403)
 await h.command('asset',{...base},sales,403)
 const filtered = await h.get(`/api/easel/scenario/${budget.id}`,board)
 assert.doesNotMatch(JSON.stringify(filtered),/Production equipment|Existing laptop/)
 assert.equal(filtered.calculation.profit[0].profit,view.calculation.profit[0].profit)
 const branch = await h.command('branch',{from:budget.id,name:'Asset alternative'})
 assert.deepEqual((await read(branch.id)).calculation,view.calculation)
 const approval = await h.command('approve-budget',{scenario:budget.id,revision:view.scenario.revision})
 const frozen = await read()
 await h.command('asset',{...base,scenario:budget.id},h.owner,409)
 await h.command('asset-category',{scenario:approval.forecast.id,name:'Vehicles',usefulLifeMonths:36})
 assert.deepEqual(await read(),frozen)
 const response = await h.mf.dispatchFetch(h.origin+`/api/easel/scenario/${budget.id}/document.xlsx`,{headers:{cookie:h.owner}})
 const book=await readWorkbook(await response.arrayBuffer());proveFormulas(book)
 assert.ok(book.getWorksheet('Fixed assets'))
 // Closed depreciation actuals stay noncash rather than becoming a payment.
 await h.command('account-map',{account:'700',target:line.id})
 await h.command('department-map',{source:'Engineering',department:dept.id})
 const body={filename:'depreciation.csv',csv:'Date,Account,Department,Amount\n2026-01-31,700,Engineering,2200\n',columns:{date:'Date',account:'Account',department:'Department',amount:'Amount'},dateFormat:'YYYY-MM-DD',amountMode:'debit-positive'}
 const p=await h.kit('actuals','preview',body);await h.kit('actuals','commit',{...body,fingerprint:p.fingerprint})
 await h.command('close-month',{scenario:approval.forecast.id,month:'2026-01'})
 const forecast=await read(approval.forecast.id)
 assert.equal(forecast.calculation.cash[0].payments,0)
 assert.equal(forecast.calculation.profit[0].profit,-220000)
})
