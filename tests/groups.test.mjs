test('ACCESS-001 group department and dimension authority, scenario shares, capability and pay grants retain live token ceilings', async t => {
 const h = await harness(); t.after(() => h.close())
 await h.command('workspace', { name: 'Synthetic Easel group planning', currency: 'USD', fiscalYearStart: 1, planStart: '2026-01' })
 const sales = await h.command('department', { name: 'Sales' }), eng = await h.command('department', { name: 'Engineering' }), legal = await h.command('department', { name: 'Legal' })
 const line = await h.command('line', { name: 'Service fees', type: 'revenue' })
 const payroll = await h.command('line', { name: 'Payroll', type: 'operating-expense', payroll: true })
 const dimension = await h.command('dimension', { name: 'Region' })
 const east = await h.command('dimension-member', { dimension: dimension.id, name: 'East' })
 const west = await h.command('dimension-member', { dimension: dimension.id, name: 'West' })
 const person = await h.person('planner@example.test', 'contributor', [legal.id], false)
 await h.command('member', { email: 'planner@example.test', name: 'Planner', role: 'contributor', departments: [], groupOnly: true })
 const board = await h.person('board@example.test', 'viewer')
 const budget = (await h.get('/api/easel/state')).scenarios[0]
 const input = { name: 'Eastern retainers', line: line.id, department: sales.id, kind: 'volume', start: '2026-01', startVolume: '2', rate: '100', dimensions: { [dimension.id]: east.id } }
 const eastInput = await h.command('revenue', { ...input, scenario: budget.id })
 await h.command('revenue', { ...input, scenario: budget.id, name: 'Western confidential agreement', dimensions: { [dimension.id]: west.id }, rate: '700' })
 await h.command('position', { scenario: budget.id, title: 'Confidential analyst', holder: 'Synthetic private employee', department: sales.id, line: payroll.id, start: '2026-01', annualSalary: '137219', dimensions: { [dimension.id]: east.id } })
 await h.command('position', { scenario: budget.id, title: 'Second analyst', holder: 'Synthetic private colleague', department: sales.id, line: payroll.id, start: '2026-01', annualSalary: '100000', dimensions: { [dimension.id]: east.id } })
 const sandbox = await h.command('sandbox-create', { from: budget.id, name: 'Group private case' })
 const tokenRequest = async (token, path, body) => {
  const response = await h.mf.dispatchFetch(h.origin + path, { method: body === undefined ? 'GET' : 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) })
  return { status: response.status, value: await response.json() }
 }
 await h.stepUp(person)
 const issue = async () => {
  const result = await h.send('/api/easel/tokens/issue', { label: 'Synthetic planner integration', kind: 'personal', scope: 'write' }, person)
  assert.equal(result.status, 200, JSON.stringify(result.value)); return result.value.token
 }
 const before = await issue()
 const definition = { name: 'Eastern planning', members: ['planner@example.test'], departments: { read: [], edit: [sales.id, eng.id], owners: [sales.id, eng.id] }, dimensions: { [dimension.id]: { read: [], edit: [east.id] } }, capabilities: [] }
 let group = await h.command('group-save', definition)
 await h.command('group-save', definition, person, 403)
 await h.command('group-pay', { id: group.id, revision: group.revision, granted: true }, person, 403)
 const report = await h.get('/api/easel/access-report')
 const authority = report.people.find(p => p.email === 'planner@example.test')
 assert.deepEqual(new Set(authority.departments.edit), new Set([sales.id, eng.id]))
 assert.equal(authority.payDetail, false)
 assert.ok(report.groups.some(g => g.id === group.id))
 await h.get('/api/easel/access-report', person, 403)
 await h.get(`/api/easel/scenario/${sandbox.id}`, person, 404)
 const share = async mode => h.command('scenario-share', { scenario: sandbox.id, revision: (await h.get(`/api/easel/scenario/${sandbox.id}`)).scenario.revision, group: group.id, mode })
 await share('read')
 const read = await h.get(`/api/easel/scenario/${sandbox.id}`, person)
 assert.ok(read.inputs.revenue.some(r => r.originId === eastInput.originId))
 assert.doesNotMatch(JSON.stringify(read), /Western confidential agreement|Synthetic private employee|13721900/)
 await h.command('revenue', { ...input, scenario: sandbox.id }, person, 403)
 assert.equal((await tokenRequest(before, `/api/easel/scenario/${sandbox.id}`)).status, 404, 'Later shares never enlarge a token')
 await share('edit')
 for (const department of [sales.id, eng.id]) await h.command('revenue', { ...input, scenario: sandbox.id, department }, person)
 await h.command('revenue', { ...input, scenario: sandbox.id, department: legal.id }, person, 403)
 await h.command('revenue', { ...input, scenario: sandbox.id, dimensions: { [dimension.id]: west.id } }, person, 403)
 await h.command('revenue', { ...input, scenario: sandbox.id, dimensions: {} }, person, 403)
 const after = await issue()
 assert.equal((await tokenRequest(after, `/api/easel/scenario/${sandbox.id}`)).status, 200)
 const bookResponse = await h.mf.dispatchFetch(h.origin + `/api/easel/scenario/${sandbox.id}/document.xlsx`, { headers: { cookie: person } })
 assert.equal(bookResponse.status, 200)
 const book = await readWorkbook(await bookResponse.arrayBuffer())
 assert.doesNotMatch(JSON.stringify(book.model), /Western confidential agreement|Synthetic private employee|13721900/)
 await h.command('line', { name: 'Unauthorized structure', type: 'revenue' }, person, 403)
 group = await h.command('group-save', { ...definition, id: group.id, revision: group.revision, capabilities: ['model-structure'] })
 await h.command('line', { name: 'Authorized planning structure', type: 'revenue' }, person)
 assert.equal((await tokenRequest(after, '/api/easel/command/line', { name: 'Token expansion refused', type: 'revenue' })).status, 403)
 group = await h.command('group-pay', { id: group.id, revision: group.revision, granted: true })
 const payRead = await h.get(`/api/easel/scenario/${sandbox.id}`, person)
 assert.match(JSON.stringify(payRead), /Synthetic private employee/)
 const oldRead = await tokenRequest(after, `/api/easel/scenario/${sandbox.id}`)
 assert.doesNotMatch(JSON.stringify(oldRead.value), /Synthetic private employee/)
 // Group authority never authorizes compensation administration.
 await h.command('group-save', { ...definition, id: group.id, revision: group.revision, members: [...definition.members, 'board@example.test'] }, person, 403)
 group = await h.command('group-pay', { id: group.id, revision: group.revision, granted: false })
 group = await h.command('group-save', { ...definition, id: group.id, revision: group.revision, members: ['board@example.test'] })
 await h.get(`/api/easel/scenario/${sandbox.id}`, person, 404)
 await h.get(`/api/easel/compare?a=${budget.id}&b=${sandbox.id}`, person, 404)
 for (const suffix of ['document.csv', 'document.xlsx']) await h.get(`/api/easel/scenario/${sandbox.id}/${suffix}`, person, 404)
 assert.equal((await tokenRequest(after, `/api/easel/scenario/${sandbox.id}`)).status, 404)
 await h.command('revenue', { ...input, scenario: sandbox.id }, person, 404)
 await h.get(`/api/easel/scenario/${sandbox.id}`, board)
 await h.command('revenue', { ...input, scenario: sandbox.id }, board, 403)
})

