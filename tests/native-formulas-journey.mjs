import assert from 'node:assert/strict'
import { join } from 'node:path'
import { api, noOverflow, settle } from './browser-journey.mjs'

/** Real Plan entry at both widths, including monetary revenue and grid refusal. */
export async function nativeFormulasJourney({ page, context, origin, budget, department, width, evidence }) {
 const cmd = (op, body) => api(context, origin, `command/${op}`, body)
 const revenue = await cmd('line', { name: `Native subscriptions ${width}`, type: 'revenue' })
 const support = await cmd('line', { name: `Native support ${width}`, type: 'cost-of-sales' })
 const name = text => `${text} ${width}`
 const card = page.locator('section.card').filter({ has: page.getByRole('heading', { name: 'Formula drivers', exact: true }) })
 const nav = text => page.getByRole('navigation', { name: 'Easel' }).getByRole('button', { name: text, exact: true }).click()
 await page.reload(); await page.getByRole('navigation', { name: 'Easel' }).waitFor()
 await nav('Plan'); await page.getByLabel('Scenario', { exact: true }).selectOption(budget.id); await settle(page)
 const row = label => card.getByRole('row').filter({ has: page.getByRole('cell', { name: name(label), exact: true }) })
 const enter = async (label, formula, { unit = 'count', line, members } = {}) => {
  await settle(page)
  await card.getByLabel('Formula driver name', { exact: true }).fill(name(label))
  await card.getByLabel('Department', { exact: true }).selectOption(department.id)
  await card.getByLabel('Unit', { exact: true }).selectOption(unit)
  if (line) { await card.getByLabel('Output line', { exact: true }).selectOption(line); await card.getByLabel('Collected after (months)', { exact: true }).selectOption('1') }
  if (members) {
   await card.getByLabel('Formula shape', { exact: true }).selectOption('dimension')
   await card.getByLabel('Dimension name', { exact: true }).fill('Region')
   for (const [i, member] of members.entries()) {
    if (i) await card.getByRole('button', { name: 'Add member', exact: true }).click()
    await card.getByLabel(`Member ${i + 1} name`, { exact: true }).fill(member.name)
    await card.getByLabel(`Member ${i + 1} formula`, { exact: true }).fill(member.formula)
   }
  } else await card.getByLabel('Formula expression', { exact: true }).fill(formula)
  await card.locator('form').scrollIntoViewIfNeeded(); await noOverflow(page, `Native formula ${label} form ${width}`)
  if (members || line) await card.locator('form').screenshot({ path: join(evidence, `native-${members ? 'region' : line === revenue.id ? 'revenue' : 'support'}-form-${width}.png`) })
  await card.getByRole('button', { name: 'Add formula driver', exact: true }).click()
  await row(label).waitFor(); await settle(page)
 }
 await enter('Customers', '100')
 await enter('Tickets per customer', '1.25')
 await enter('Cost per ticket', null, { unit: 'money', members: [{ name: 'East', formula: '2.22' }, { name: 'West', formula: '3.33' }] })
 const expression = `DRIVER("${name('Tickets per customer')}") * LOOKUP("${name('Cost per ticket')}", "Region", "West") * DRIVER("${name('Customers')}")`
 await enter('Regional support', expression, { unit: 'money', line: support.id })
 await enter('Subscription revenue', `DRIVER("${name('Customers')}") * 50`, { unit: 'money', line: revenue.id })
 let view = await api(context, origin, `scenario/${budget.id}`)
 const cell = line => view.calculation.cells.find(c => c.line === line && c.month === '2026-01')
 assert.equal(cell(support.id).amount, 41600); assert.equal(cell(revenue.id).amount, 500000)
 const nativeSource = cell(support.id).sources.find(s => s.kind === 'formula')
 assert.match(nativeSource.trace, /1\.25/); assert.match(nativeSource.trace, /3\.33/)
 await row('Customers').getByRole('button', { name: 'Edit', exact: true }).click()
 await card.getByLabel('Formula expression', { exact: true }).fill('120')
 await card.getByRole('button', { name: 'Save formula driver', exact: true }).click()
 await card.getByRole('button', { name: 'Add formula driver', exact: true }).waitFor(); await settle(page)
 view = await api(context, origin, `scenario/${budget.id}`)
 assert.equal(cell(revenue.id).amount, 600000); assert.equal(cell(support.id).amount, 49920)
 await page.reload(); await page.getByRole('navigation', { name: 'Easel' }).waitFor(); await nav('Plan')
 await page.getByLabel('Scenario', { exact: true }).selectOption(budget.id); await settle(page)
 await row('Customers').getByRole('button', { name: 'Edit', exact: true }).click()
 assert.equal(await card.getByLabel('Formula expression', { exact: true }).inputValue(), '120')
 await card.getByLabel('Formula expression', { exact: true }).fill(`DRIVER("${name('Regional support')}")`)
 await card.getByRole('button', { name: 'Save formula driver', exact: true }).click()
 await card.getByRole('alert').waitFor()
 const error = await card.getByRole('alert').innerText()
 assert.match(error, /circular|cycle/i); assert.ok(error.includes(name('Customers')) && error.includes(name('Regional support')))
 assert.deepEqual(await api(context, origin, `scenario/${budget.id}`), view)
 await card.getByRole('button', { name: 'Cancel editing', exact: true }).click()
 await card.getByText('Calculated driver values and traces (read-only)', { exact: true }).click()
 const values = card.getByRole('region', { name: 'Computed formula drivers', exact: true })
 assert.equal(await values.locator('input,textarea,select').count(), 0)
 const computed = values.getByRole('row').filter({ has: page.getByRole('cell', { name: name('Regional support'), exact: true }) }).filter({ has: page.getByRole('cell', { name: 'Jan 2026', exact: true }) })
 assert.ok((await computed.innerText()).includes('$499.20'))
 assert.ok((await computed.innerText()).includes('1.25'))
 await computed.scrollIntoViewIfNeeded(); await noOverflow(page, `Native computed values ${width}`)
  await page.screenshot({ path: join(evidence, `native-values-${width}.png`) })
 await card.getByText('Calculated driver values and traces (read-only)', { exact: true }).click()
 await card.scrollIntoViewIfNeeded(); await card.screenshot({ path: join(evidence, `native-definitions-${width}.png`) })

 // Typing over a derived total is refused, including a real entered row on that line.
 const schedule = await cmd('schedule', { scenario: budget.id, name: name('Formula grid row'), line: support.id, department: department.id, values: { '2026-01': '0' } })
 await page.reload(); await page.getByRole('navigation', { name: 'Easel' }).waitFor(); await nav('Plan')
 await page.getByLabel('Scenario', { exact: true }).selectOption(budget.id); await settle(page)
 const grid = page.locator('section.card').filter({ has: page.getByRole('heading', { name: 'Planning grid', exact: true }) })
 await grid.getByLabel(`${name('Formula grid row')} Jan 2026 grid amount`, { exact: true }).fill('9')
 await grid.getByRole('button', { name: 'Preview cell edits', exact: true }).click()
 await grid.getByRole('heading', { name: 'Review grid changes', exact: true }).waitFor()
 assert.equal(await grid.getByRole('button', { name: 'Apply grid changes', exact: true }).isDisabled(), true)
 assert.match(await grid.getByRole('alert').innerText(), /refused/i)
 assert.equal((await api(context, origin, `scenario/${budget.id}`)).inputs.schedule.find(s => s.id === schedule.id).values['2026-01'], 0)
 await grid.getByText('Calculated cells and their traces (read-only)', { exact: true }).click()
 const calculated = grid.getByRole('region', { name: 'Read-only calculated planning cells', exact: true })
 const calculatedRow = calculated.getByRole('row').filter({ has: page.getByRole('rowheader', { name: new RegExp(support.name) }) })
 assert.equal(await calculatedRow.locator('input,textarea,select').count(), 0)
 await calculatedRow.getByText('Trace Jan 2026', { exact: true }).click()
 assert.ok((await calculatedRow.innerText()).includes('1.25'))
 await calculatedRow.scrollIntoViewIfNeeded(); await noOverflow(page, `Native formula grid ${width}`)
 await grid.screenshot({ path: join(evidence, `native-grid-refusal-${width}.png`) })
 console.log(`Native formulas ${width}: scalar and Region table, revenue/support entry, exact traces, edit/reload, named cycle and refused grid typing passed`)
}
