import test from 'node:test'
import assert from 'node:assert/strict'
import ExcelJS from 'exceljs'
import { harness } from './harness.mjs'

test('ENTITY-001 local entity plans translate independently and eliminate reviewed source-backed charges, balances and settlements', async t => {
 const h = await harness(); t.after(() => h.close())
 await h.command('workspace', { name: 'Synthetic entity planning', currency: 'USD', fiscalYearStart: 1, planStart: '2026-01' })
 const department = await h.command('department', { name: 'Operations' })
 const revenue = await h.command('line', { name: 'Management services', type: 'revenue' })
 const expense = await h.command('line', { name: 'Management expense', type: 'operating-expense' })
 const parent = (await h.get('/api/easel/state')).scenarios[0]
 const subsidiary = await h.command('branch', { from: parent.id, name: 'Services entity plan' })
 const from = await h.command('entity-save', { name: 'Canadian entity', scenario: parent.id, currency: 'CAD', group: parent.id, reporting: 'USD' })
 const to = await h.command('entity-save', { name: 'European entity', scenario: subsidiary.id, currency: 'EUR', group: parent.id, reporting: 'USD' })
 for (const scenario of [parent.id, subsidiary.id]) await h.command('scenario-cash', { scenario, basis: 'estimate', opening: '10000', collectionLag: 1, paymentLag: 1 })
 const charge = await h.command('revenue', { scenario: parent.id, name: 'Intercompany services', kind: 'volume', department: department.id, line: revenue.id, start: '2026-01', startVolume: '1', rate: '100', collectionLag: 1 })
 const cost = await h.command('expense', { scenario: subsidiary.id, name: 'Intercompany services received', kind: 'recurring', department: department.id, line: expense.id, start: '2026-01', amount: '80' })
 const payroll = await h.command('line', { name: 'People costs', type: 'operating-expense', payroll: true })
 await h.command('position', { scenario: parent.id, title: 'Confidential entity analyst', holder: 'Synthetic private entity employee', department: department.id, line: payroll.id, start: '2026-03', annualSalary: '83000' })
 const path = `/api/easel/consolidation/${parent.id}`
 let view = await h.get(path)
 assert.equal(view.entities[0].translated.months[0].profit, null, 'local currency amounts are never treated as reporting currency without rates')
 assert.equal(view.consolidated[0].profit, null)
 for (const [entity, opening, average, end] of [[from, '0.70', '0.80', '0.90'], [to, '0.90', '1', '1.125']]) {
  await h.command('entity-rate', { entity: entity.id, month: '2025-12', monthEnd: opening })
  await h.command('entity-rate', { entity: entity.id, month: '2026-01', budget: average, average, monthEnd: end })
  await h.command('entity-rate', { entity: entity.id, month: '2026-02', budget: average, average, monthEnd: average })
 }
 const rule = { name: 'Reviewed reciprocal management charge', group: parent.id, fromEntity: from.id, toEntity: to.id, fromOrigin: charge.originId, toOrigin: cost.originId, fromAmount: '100', toAmount: '80', receivable: '100', payable: '80', cashReceived: '0', cashPaid: '0', reviewed: true }
 await h.command('entity-elimination-save', { ...rule, month: '2026-01', reviewed: false }, h.owner, 400)
 await h.command('entity-elimination-save', { ...rule, month: '2026-01', toAmount: '81' }, h.owner, 409)
 const january = await h.command('entity-elimination-save', { ...rule, month: '2026-01' })
 await h.command('entity-elimination-save', { ...rule, month: '2026-01' }, h.owner, 409)
 await h.command('entity-elimination-save', { ...rule, name: 'February charge and January settlement', month: '2026-02', cashReceived: '100', cashPaid: '80' })
 view = await h.get(path)
 assert.equal(view.scope, 'complete')
 assert.doesNotMatch(JSON.stringify(view), /Synthetic private entity employee|Confidential entity analyst|annualSalary|originId/)
 const canadian = view.entities.find(e => e.id === from.id), european = view.entities.find(e => e.id === to.id)
 assert.deepEqual([canadian.local.currency, european.local.currency], ['CAD', 'EUR'])
 assert.deepEqual([canadian.local.profit[0].revenue, european.local.profit[0].operatingExpenses], [10000, 8000])
 assert.deepEqual([canadian.translated.months[0].profit.revenue, european.translated.months[0].profit.operatingExpenses], [8000, 8000])
 assert.deepEqual([canadian.translated.months[0].balanceSheet.receivables, european.translated.months[0].balanceSheet.payables], [9000, 9000])
 for (const [i, expectedBalance, cashEliminated] of [[0, 9000, 0], [1, 8000, 8000]]) {
  const row = view.consolidated[i]
  assert.deepEqual(row.unavailable, [])
  assert.deepEqual([row.profit.revenue, row.profit.operatingExpenses, row.profit.profit], [0, 0, 0])
  assert.equal(row.balanceSheet.receivables, 0); assert.equal(row.balanceSheet.payables, 0)
  assert.equal(row.before.balanceSheet.assets - row.balanceSheet.assets, expectedBalance)
  assert.equal(row.before.balanceSheet.liabilities - row.balanceSheet.liabilities, expectedBalance)
  assert.equal(row.before.cash.collections - row.cash.collections, cashEliminated)
  assert.equal(row.before.cash.payments - row.cash.payments, cashEliminated)
  assert.equal(row.cash.closing, canadian.translated.months[i].cash.closing + european.translated.months[i].cash.closing)
  assert.equal(row.cash.difference, 0); assert.equal(row.balanceSheet.balanceDifference, 0)
  assert.equal(row.balanceSheet.assets, row.balanceSheet.liabilities + row.balanceSheet.equity + row.balanceSheet.translationAdjustment)
  for (const statement of ['profit', 'balanceSheet', 'cash']) for (const [key, before] of Object.entries(row.before[statement])) {
   const sum = view.entities.reduce((n, entity) => n + entity.translated.months[i][statement][key], 0)
   assert.equal(before, sum, `${statement}.${key} is summed only after entity translation`)
  }
 }
 assert.notEqual(view.consolidated[0].balanceSheet.translationAdjustment, 0, 'translation differences stay visible')
 assert.equal(view.consolidated[2].profit, null, 'missing future rates remain unavailable')
 const download = await h.mf.dispatchFetch(`${h.origin}${path}/workbook`, { headers: { cookie: h.owner } })
 assert.equal(download.status, 200)
 const book = new ExcelJS.Workbook(); await book.xlsx.load(Buffer.from(await download.arrayBuffer()))
 const sheet = book.getWorksheet('Profit and loss')
 assert.equal(sheet.getCell('G3').result, view.consolidated[0].profit.revenue)
 assert.ok(sheet.getCell('G3').formula, 'the downloaded total remains an Excel formula')
 assert.equal(sheet.getCell('E3').result - sheet.getCell('F3').value, sheet.getCell('G3').result)
 const viewer = await h.person('synthetic-entity-reader@example.test', 'viewer')
 const subsidiaryVersion = await h.command('branch', { from: subsidiary.id, name: 'European entity revision' })
 assert.equal((await h.get(path, viewer)).consolidated[0].profit.profit, 0)
 await h.command('entity-rate', { entity: from.id, month: '2026-01', average: '1' }, viewer, 403)
 await h.command('entity-save', { name: 'Denied', scenario: parent.id, currency: 'CAD' }, viewer, 403)
 await h.command('entity-elimination-delete', { id: january.id }, viewer, 403)
 await h.command('member', { email: 'synthetic-entity-reader@example.test', name: 'Canadian reader', role: 'viewer', dimensionMembers: { [from.dimension]: [from.member] } })
 assert.deepEqual((await h.get('/api/easel/entities', viewer)).entities.map(e => e.id), [from.id])
 const ownPlan = await h.get(`/api/easel/scenario/${parent.id}`, viewer)
 assert.equal(ownPlan.workspace.currency, 'CAD')
 assert.equal(ownPlan.calculation.profit[0].revenue, 10000)
 assert.doesNotMatch(JSON.stringify(ownPlan.calculation), /originId|annualSalary|holder/)
 await h.get(`/api/easel/scenario/${subsidiary.id}`, viewer, 404)
 await h.get(`/api/easel/scenario/${subsidiaryVersion.id}`, viewer, 404)
 assert.ok(!(await h.get('/api/easel/state', viewer)).scenarios.some(s => s.id === subsidiary.id))
 const restricted = await h.get(path, viewer)
 assert.equal(restricted.scope, 'restricted'); assert.equal(restricted.consolidated[0].profit, null)
 assert.ok(!JSON.stringify(restricted).includes('European entity'))
 await h.command('department', { name: 'Restricted department' })
 await h.command('member', { email: 'synthetic-entity-reader@example.test', name: 'Canadian reader', role: 'viewer', groupOnly: true })
 await h.command('group-save', { name: 'Entity Operations readers', members: ['synthetic-entity-reader@example.test'], departments: { read: [department.id] }, dimensions: { [from.dimension]: { read: [from.member] } } })
 await h.get(path, viewer, 403)
 assert.equal((await h.get(`/api/easel/scenario/${parent.id}`, viewer)).calculation.profit[0].revenue, 10000)
 await h.command('member', { email: 'synthetic-entity-reader@example.test', name: 'Canadian reader', role: 'viewer', groupOnly: false, dimensionMembers: { [from.dimension]: [from.member] } })
 // A later source edit invalidates the reviewed rule rather than silently exceeding its source amount.
 await h.command('revenue', { ...charge, id: charge.id, scenario: parent.id, rate: '50', startVolume: '1', growthPercent: '0' })
 const stale = await h.get(path)
 assert.equal(stale.consolidated[0].profit, null)
 assert.match(stale.consolidated[0].unavailable.join(' '), /exceeds the selected source/)
})
