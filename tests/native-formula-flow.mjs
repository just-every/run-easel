import assert from 'node:assert/strict'
import JSZip from 'jszip'
import { readWorkbook, proveFormulas } from './spreadsheet-proof.mjs'

export async function nativeFormulaFlow(h) {
 await h.command('workspace', { name: 'Cedar Support Studio', currency: 'USD', fiscalYearStart: 1, planStart: '2026-01' })
 const department = await h.command('department', { name: 'Customer success' })
 const other = await h.command('department', { name: 'Operations' })
 const revenue = await h.command('line', { name: 'Formula subscriptions', type: 'revenue' })
 const support = await h.command('line', { name: 'Regional support', type: 'cost-of-sales' })
 const rounding = await h.command('line', { name: 'Division arithmetic', type: 'operating-expense' })
 const budget = (await h.get('/api/easel/state')).scenarios[0]
 const view = (id = budget.id, who = h.owner) => h.get(`/api/easel/scenario/${id}`, who)
 const save = async (fields, scenario = budget.id, who = h.owner) => h.command('formula', {
  scenario, revision: (await view(scenario, who)).scenario.revision,
  department: department.id, unit: 'count', start: '2026-01', ...fields,
 }, who)
 const customers = await save({ name: 'Customers', formula: '100' })
 await save({ name: 'Tickets per customer', formula: '1.25' })
 const cost = await save({ name: 'Cost per ticket', unit: 'money', dimension: 'Region', members: [{ name: 'East', formula: '2.22' }, { name: 'West', formula: '3.33' }] })
 await save({ name: 'Support by region', unit: 'money', dimension: 'Region', members: [
  { name: 'East', formula: 'DRIVER("Tickets per customer") * LOOKUP("Cost per ticket", "Region", MEMBER()) * DRIVER("Customers")' },
  { name: 'West', formula: 'DRIVER("Tickets per customer") * LOOKUP("Cost per ticket", "Region", MEMBER()) * DRIVER("Customers")' },
 ] })
 const total = await save({ name: 'Support cost', unit: 'money', line: support.id, formula: 'SUM("Support by region", "Region")' })
 const subscription = await save({ name: 'Subscription revenue', unit: 'money', line: revenue.id, collectionLag: 1, formula: 'DRIVER("Customers") * 50' })
 await save({ name: 'Rounded division', unit: 'money', line: rounding.id, formula: 'LINE("Formula subscriptions", "Customer success") / 3 * 3' })
 await save({ name: 'Customer growth', formula: 'IF(PERIOD() = 1, 100, GROWTH(PRIOR("Customer growth"), 10))' })
 await save({ name: 'Signed rounding', unit: 'money', formula: 'IF(1 = 1, ROUND(MIN(MAX(-1.50, -2), -1), 0), 1 / 0)' })
 let current = await view()
 const cell = (v, line, month = '2026-01') => v.calculation.cells.find(c => c.line === line && c.department === department.id && c.month === month)
 const value = (v, name, month = '2026-01', member) => v.calculation.formulaValues.find(c => c.name === name && c.month === month && c.member === member)
 assert.equal(cell(current, support.id).amount, 69400, '125 tickets × regional unit rates, rounded at each division: East 278.00 plus West 416.00')
 assert.equal(cell(current, revenue.id).amount, 500000)
 assert.equal(cell(current, rounding.id).amount, 500001, '5000 / 3 rounds to 1666.67 before multiplication by 3')
 assert.deepEqual(['2026-01', '2026-02', '2026-03'].map(m => value(current, 'Customer growth', m).value), [10000, 11000, 12100])
 assert.equal(value(current, 'Signed rounding').value, -200, 'negative ties round away from zero; the unused divide-by-zero branch is lazy')
 assert.equal(value(current, 'Support by region', '2026-01', 'East').value, 27800)
 assert.equal(value(current, 'Support by region', '2026-01', 'West').value, 41600)
 assert.equal(current.calculation.cash[0].collections, 0)
 assert.equal(current.calculation.cash[1].collections, 500000, 'native formula revenue uses its explicit collection lag')
 for (const name of ['Customers', 'Cost per ticket', 'Support by region', 'Support cost', 'Subscription revenue', 'Rounded division', 'Customer growth']) {
  const values = current.calculation.formulaValues.filter(v => v.name === name)
  assert.ok(values.length > 0)
  for (const v of values) assert.ok(typeof v.trace === 'string' && v.trace.includes(name), `${name}: exact cell trace names its definition`)
 }
 assert.match(cell(current, support.id).sources.find(s => s.id === total.originId).trace, /East.*West|West.*East/)
 assert.match(value(current, 'Support by region', '2026-01', 'West').trace, /1\.25.*3\.33|3\.33.*1\.25/)
 for (const month of current.calculation.balanceSheet) assert.equal(month.balanceDifference, 0)

 // Every refusal uses the real command, and leaves both model and trail intact.
 const refusal = async (body, pattern) => {
  const before = await view(), activity = await h.get('/api/easel/activity')
  const result = await h.send('/api/easel/command/formula', { scenario: budget.id, revision: before.scenario.revision, department: department.id, unit: 'count', start: '2026-01', ...body }, h.owner)
  assert.ok([400, 409].includes(result.status), JSON.stringify(result.value))
  assert.match(result.value.error, pattern)
  assert.deepEqual(await view(), before)
  assert.deepEqual(await h.get('/api/easel/activity'), activity)
 }
 await refusal({ name: 'Customers', id: customers.id, formula: 'DRIVER("Support cost")' }, /Customers.*Support cost.*Support by region.*Customers|Customers.*Support by region.*Support cost.*Customers|cycle.*Customers/i)
 await refusal({ name: 'Broken arithmetic', formula: '1 / 0' }, /zero/i)
 await refusal({ name: 'Missing driver', formula: 'DRIVER("Does not exist")' }, /Does not exist/)
 await refusal({ name: 'Missing region', formula: 'LOOKUP("Cost per ticket", "Region", "North")' }, /North/)
 await refusal({ name: 'Stale save', formula: '1', revision: current.scenario.revision - 1 }, /changed|revision|reload/i)
 const deleteResult = await h.send('/api/easel/command/input-delete', { kind: 'formula', id: cost.id }, h.owner)
 assert.ok([400, 409].includes(deleteResult.status)); assert.deepEqual(await view(), current)

 const schedule = await h.command('schedule', { scenario: budget.id, name: 'Support grid entry', line: support.id, department: department.id, values: { '2026-01': '0' } })
 current = await view()
 const request = { scenario: budget.id, revision: current.scenario.revision, changes: [{ schedule: schedule.id, month: '2026-01', value: '10' }] }
 const preview = await h.command('grid-preview', request)
 assert.ok(preview.refused.length > 0)
 assert.match(JSON.stringify(preview.refused), /calculated|driver|formula/i)
 await h.command('grid-save', { ...request, fingerprint: preview.fingerprint }, h.owner, 400)
 assert.deepEqual(await view(), current)

 const contributor = await h.person('support@example.test', 'contributor', [department.id])
 const outsider = await h.person('operations@example.test', 'contributor', [other.id])
 const board = await h.person('board@example.test', 'viewer')
 await h.command('request-submissions', { scenario: budget.id, departments: [department.id] })
 await h.command('formula', { scenario: budget.id, revision: (await view()).scenario.revision, name: 'Forbidden output', department: department.id, unit: 'money', formula: '1', line: support.id }, outsider, 403)
 await h.command('formula', { scenario: budget.id, revision: (await view()).scenario.revision, name: 'Forbidden output', department: department.id, unit: 'money', formula: '1', line: support.id }, board, 403)
 for (const who of [outsider, board]) {
  const filtered = await view(budget.id, who)
  assert.equal(cell(filtered, support.id).amount, 69400)
  assert.equal(filtered.inputs.formula.length, 0)
  assert.ok(!filtered.calculation.formulaValues?.length)
  assert.doesNotMatch(JSON.stringify(filtered), /Tickets per customer|Cost per ticket|Support by region/)
 }
 await h.command('submit', { scenario: budget.id, department: department.id }, contributor)
 const approved = await h.command('approve-budget', { scenario: budget.id, revision: (await view()).scenario.revision })
 const forecast = approved.forecast
 const frozenBudget = await view()
 const kept = await h.command('reforecast-save', { from: forecast.id, revision: forecast.revision, name: 'Native formula outlook' })
 const frozenKept = await view(kept.id)

 // A proposal carries formulas through HTTP/MCP, exact diffs and human promotion.
 const proposal = await h.command('proposal-create', { from: forecast.id, name: 'Support expansion', request: 'Serve 120 customers' }, contributor)
 const draft = await view(proposal.id, contributor), proposalCustomers = draft.inputs.formula.find(f => f.originId === customers.originId)
 const response = await h.send('/api/easel/mcp', { jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name: 'formula', arguments: { scenario: proposal.id, revision: String(draft.scenario.revision), id: proposalCustomers.id, name: 'Customers', department: department.id, unit: 'count', start: '2026-01', formula: '120' } } }, contributor)
 assert.equal(response.status, 200); assert.equal(response.value.result.isError, undefined, JSON.stringify(response.value))
 const comparison = await h.get(`/api/easel/compare?a=${forecast.id}&b=${proposal.id}`, contributor)
 assert.ok(comparison.changedInputs.some(c => c.after?.formula === '120' && c.before?.formula === '100'))
 assert.equal(comparison.changedCells.find(c => c.line === revenue.id && c.month === '2026-01').difference, 100000)
 assert.equal(cell(await view(forecast.id), revenue.id).amount, 500000)
 await h.command('proposal-submit', { id: proposal.id }, contributor)
 const submitted = await view(proposal.id, contributor)
 await h.command('proposal-promote', { id: proposal.id, revision: submitted.scenario.revision - 1 }, h.owner, 409)
 await h.command('proposal-promote', { id: proposal.id, revision: submitted.scenario.revision })
 assert.equal(cell(await view(forecast.id), revenue.id).amount, 600000)
 assert.equal(cell(await view(forecast.id), support.id).amount, 83280)
 const events = await h.get(`/api/easel/activity?action=structure-version&scenario=${proposal.id}`)
 const event = events.find(v => v.detail.changes.some(c => c.kind === 'formula' && c.fields.some(f => f.field === 'formula' && f.before === '100' && f.after === '120')))
 assert.ok(event, 'readable formula diff retained in exact structure version')
 const changed = event.detail.changes.find(c => c.kind === 'formula' && c.after?.name === 'Customers')
 assert.equal(changed.before.formula, '100'); assert.equal(changed.after.formula, '120')
 const moved = event.detail.scenarios.find(s => s.id === proposal.id)
 assert.ok(moved.changedCells.some(c => c.line === support.id && c.before === 69400 && c.after === 83280 && c.difference === 13880))

 await nativeHistoryAndFrozen(h, { department, revenue, support, rounding, forecast, subscription, save, view, cell, frozenBudget, kept, frozenKept, customers })
 await nativeVersionFlow(h, { department, revenue, save, view, kept, customers })
}

async function nativeHistoryAndFrozen(h, f) {
 const { department, revenue, support, forecast, save, view, cell, frozenBudget, kept, frozenKept, customers } = f
 await h.command('account-map', { account: '400', target: revenue.id })
 await h.command('department-map', { source: 'Support', department: department.id })
 const body = { filename: 'native-history.csv', csv: 'Date,Account,Department,Amount\n2025-11-30,400,Support,0\n2025-12-31,400,Support,-0.01\n2026-01-31,400,Support,-4800\n', columns: { date: 'Date', account: 'Account', department: 'Department', amount: 'Amount' }, dateFormat: 'YYYY-MM-DD', amountMode: 'debit-positive' }
 const preview = await h.kit('actuals', 'preview', body)
 await h.kit('actuals', 'commit', { ...body, fingerprint: preview.fingerprint })
 await save({ name: 'Historical rounding', unit: 'money', formula: 'IF(PERIOD() = 1, ACTUAL("Formula subscriptions", "Customer success", -1) / 2, 0)' }, forecast.id)
 await save({ name: 'Accepted zero', unit: 'money', formula: 'IF(PERIOD() = 1, ACTUAL("Formula subscriptions", "Customer success", -2), 0)' }, forecast.id)
 await save({ name: 'Captured version', unit: 'money', formula: `IF(PERIOD() = 1, 0, VERSION("${kept.id}", "Formula subscriptions", "Customer success", -1))` }, forecast.id)
 let current = await view(forecast.id)
 assert.equal(current.calculation.formulaValues.find(v => v.name === 'Historical rounding' && v.month === '2026-01').value, 1)
 assert.equal(current.calculation.formulaValues.find(v => v.name === 'Accepted zero' && v.month === '2026-01').value, 0)
 assert.equal(current.calculation.formulaValues.find(v => v.name === 'Captured version' && v.month === '2026-02').value, 500000)
 assert.match(current.calculation.formulaValues.find(v => v.name === 'Historical rounding' && v.month === '2026-01').trace, /2025-12|Dec 2025/)
 const bad = await h.send('/api/easel/command/formula', { scenario: forecast.id, revision: current.scenario.revision, department: department.id, name: 'Missing history', unit: 'money', formula: 'ACTUAL("Formula subscriptions", "Customer success", -24)' }, h.owner)
 assert.ok([400, 409].includes(bad.status)); assert.match(bad.value.error, /missing|unavailable|accepted|source/i)
 assert.deepEqual(await view(forecast.id), current)
 await h.command('close-month', { scenario: forecast.id, month: '2026-01' })
 const pack = await h.command('pack-create', { forecast: forecast.id, month: '2026-01', title: 'Native formulas January' })
 const published = await h.command('pack-publish', { pack: pack.id })
 const snapshots = await Promise.all((await h.get('/api/easel/state')).snapshots.map(s => h.get(`/api/easel/snapshot/${s.id}`)))
 const exportBefore = await h.mf.dispatchFetch(`${h.origin}/api/easel/export`, { headers: { cookie: h.owner } })
 assert.equal(exportBefore.status, 200)
 const archive = await JSZip.loadAsync(await exportBefore.arrayBuffer())
 const privatePackPath = Object.keys(archive.files).find(p => p.includes(published.snapshot) && p.endsWith('.json'))
 assert.ok(privatePackPath)
 const privatePack = JSON.parse(await archive.file(privatePackPath).async('string'))
 assert.match(JSON.stringify(privatePack), /Customers.*120|120.*Customers/, 'complete export retains the pack’s captured native definitions')
 current = await view(forecast.id)
 const row = current.inputs.formula.find(f => f.originId === customers.originId)
 await save({ id: row.id, name: row.name, formula: '150' }, forecast.id)
 assert.equal(cell(await view(forecast.id), revenue.id, '2026-02').amount, 750000)
 assert.equal(cell(await view(forecast.id), revenue.id).amount, 480000, 'closed actuals remain authoritative')
 await h.command('line', { ...support, name: 'Support renamed after publication' })
 assert.deepEqual(await view(frozenBudget.scenario.id), frozenBudget)
 assert.deepEqual(await view(kept.id), frozenKept)
 for (const snapshot of snapshots) assert.deepEqual(await h.get(`/api/easel/snapshot/${snapshot.id}`), snapshot)
 const workbook = await h.mf.dispatchFetch(`${h.origin}/api/easel/scenario/${forecast.id}/document.xlsx`, { headers: { cookie: h.owner } })
 assert.equal(workbook.status, 200); proveFormulas(await readWorkbook(await workbook.arrayBuffer()))
}

async function nativeVersionFlow(h, { department, revenue, save, view, kept, customers }) {
 const source = await h.command('branch', { from: kept.id, name: 'Formula source version' })
 const consumer = await h.command('branch', { from: kept.id, name: 'Formula consumer version' })
 await save({ name: 'Offset working version', unit: 'money', formula: `IF(PERIOD() = 1, 0, VERSION("${source.id}", "Formula subscriptions", "Customer success", -1))` }, consumer.id)
 let current = await view(consumer.id)
 const amount = v => v.calculation.formulaValues.find(f => f.name === 'Offset working version' && f.month === '2026-02').value
 assert.equal(amount(current), 500000)
 const proposal = await h.command('proposal-create', { from: consumer.id, name: 'Reviewed source dependency', request: 'Keep the current version link' })
 await h.command('proposal-submit', { id: proposal.id })
 const submitted = await view(proposal.id)
 const sourceCustomer = (await view(source.id)).inputs.formula.find(f => f.originId === customers.originId)
 await save({ id: sourceCustomer.id, name: sourceCustomer.name, formula: '130' }, source.id)
 const changed = await view(consumer.id)
 assert.equal(amount(changed), 650000)
 assert.ok(changed.scenario.revision > current.scenario.revision, 'a working version dependency changes the consumer revision')
 const staleProposal = await view(proposal.id)
 assert.ok(staleProposal.scenario.revision > submitted.scenario.revision)
 await h.command('proposal-promote', { id: proposal.id, revision: staleProposal.scenario.revision }, h.owner, 409)

 const shared = await h.command('department', { name: 'Shared support centre', shared: true })
 const line = await h.command('line', { name: 'Allocated support cost', type: 'operating-expense' })
 await h.command('expense', { scenario: consumer.id, name: 'Shared vendor cost', line: line.id, department: shared.id, kind: 'recurring', start: '2026-01', amount: '100' })
 await h.command('allocation', { scenario: consumer.id, name: 'Support centre allocation', sourceDepartment: shared.id, basis: 'fixed', targets: [{ department: department.id, percent: '100' }] })
 await save({ name: 'Final allocated line', unit: 'money', formula: 'LINE("Allocated support cost", "Customer success")' }, consumer.id)
 current = await view(consumer.id)
 assert.equal(current.calculation.formulaValues.find(f => f.name === 'Final allocated line' && f.month === '2026-01').value, 10000, 'LINE reads the final allocated amount')
 const actualCell = current.calculation.cells.find(c => c.line === line.id && c.department === department.id && c.month === '2026-01')
 assert.equal(actualCell.amount, 10000)
 const rounding = current.inputs.formula.find(f => f.name === 'Rounded division')
 await save({ id: rounding.id, name: rounding.name, unit: 'money', line: rounding.line, formula: '0' }, consumer.id)
 const taxLine = await h.command('line', { name: 'Native income tax', type: 'operating-expense' })
 await h.command('tax-policy', { scenario: consumer.id, line: taxLine.id, department: department.id, sutaPercent: '0', sutaBase: '0', federalIncomePercent: '10', stateIncomePercent: '0', salesTaxPercent: '0' })
 await save({ name: 'Prior period tax', unit: 'money', formula: 'IF(PERIOD() = 1, 0, LINE("Native income tax", "Customer success", -1))' }, consumer.id)
 current = await view(consumer.id)
 assert.equal(current.calculation.cells.find(c => c.line === taxLine.id && c.month === '2026-01').amount, 42060)
 assert.equal(current.calculation.formulaValues.find(f => f.name === 'Prior period tax' && f.month === '2026-02').value, 42060, 'LINE reads final income-tax arithmetic at the requested offset')
 const consumerRevenue = current.inputs.formula.find(f => f.line === revenue.id)
 await save({ id: consumerRevenue.id, name: consumerRevenue.name, unit: 'money', line: revenue.id, formula: `VERSION("${source.id}", "Formula subscriptions", "Customer success")` }, consumer.id)
 const sourceBefore = await view(source.id), consumerBefore = await view(consumer.id)
 const sourceRevenue = sourceBefore.inputs.formula.find(f => f.line === revenue.id)
 const cycle = await h.send('/api/easel/command/formula', { scenario: source.id, revision: sourceBefore.scenario.revision, id: sourceRevenue.id, name: sourceRevenue.name, department: department.id, unit: 'money', line: revenue.id, formula: `VERSION("${consumer.id}", "Formula subscriptions", "Customer success")` }, h.owner)
 assert.equal(cycle.status, 409)
 assert.match(cycle.value.error, /circular|cycle/i)
 assert.ok(cycle.value.error.includes('Formula source version') && cycle.value.error.includes('Formula consumer version'), 'the cross-version cycle names both versions')
 assert.deepEqual(await view(source.id), sourceBefore); assert.deepEqual(await view(consumer.id), consumerBefore)
}
