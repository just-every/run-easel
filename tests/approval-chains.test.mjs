 const engineeringInput = await h.command('revenue', { ...input, name: 'Engineering retainers', department: eng.id })
 const view = (cookie = h.owner) => h.get(`/api/easel/approval-chains/${budget.id}`, cookie)
 const row = async (cookie = h.owner) => (await view(cookie)).departments.find(d => d.department === sales.id)
 const sub = async () => (await row()).submission
 const approve = async (cookie, index, status = 200, body = {}) => { const r = await row(); return h.command('approval-step', { scenario: budget.id, department: sales.id, step: r.steps[index].id, pass: r.submission.review.pass, digest: r.submission.review.content.digest, ...body }, cookie, status) }
 const approveBudget = async (status = 200, cookie = h.owner) => h.command('approve-budget', { scenario: budget.id, revision: (await h.get(`/api/easel/scenario/${budget.id}`)).scenario.revision }, cookie, status)
 const editGroup = async changes => { group = await h.command('group-save', { ...group, payDetail: undefined, ...changes }); return group }
 await h.command('approval-chain-save', { department: sales.id, steps: [{ name: 'Department head', groups: [group.id] }] }, reviewer, 403)
 let chain = await h.command('approval-chain-save', { department: sales.id, steps: [{ name: 'Department head', groups: [group.id] }, { name: 'Finance planner', members: ['planner@example.test'] }] })
 await h.command('request-submissions', { scenario: budget.id, departments: [sales.id, eng.id] })
 await h.command('submit', { scenario: budget.id, department: eng.id }, engineer)
 assert.equal((await view()).departments.find(d => d.department === eng.id).submission.status, 'submitted')
 await h.command('submit', { scenario: budget.id, department: sales.id }, submitter)
 assert.equal((await sub()).status, 'reviewing')
 await h.command('revenue', { ...input, id: first.id, rate: '150' }, submitter, 409)
 await approve(planner, 1, 409)
 await approve(viewer, 0, 403)
 assert.match((await approveBudget(409)).error, /Sales.*Department head/)
 const notices = h.messages.filter(m => m.subject?.startsWith('Department review pending'))
 assert.deepEqual(notices.map(m => m.to), [['head@example.test']])
 await editGroup({ members: [] })
 assert.equal((await row()).steps[0].status, 'blocked')
 await approve(reviewer, 0, 403)
 await editGroup({ members: ['head@example.test'], dimensions: { [region.id]: { read: [east.id] } } })
 await approve(reviewer, 0, 403)
 assert.equal((await row()).steps[0].status, 'blocked')
 await editGroup({ dimensions: { [region.id]: { read: [east.id, west.id] } } })
 // A named service credential keeps the person's scope but cannot decide.
 await h.stepUp(reviewer)
 const issued = await h.send('/api/easel/tokens/issue', { label: 'Synthetic Easel review agent', kind: 'service', scope: 'write' }, reviewer)
 assert.equal(issued.status, 200)
 const pending = await row()
 const agentResponse = await h.mf.dispatchFetch(h.origin + '/api/easel/command/approval-step', { method: 'POST', headers: { authorization: `Bearer ${issued.value.token}`, 'content-type': 'application/json' }, body: JSON.stringify({ scenario: budget.id, department: sales.id, step: pending.steps[0].id, pass: pending.submission.review.pass, digest: pending.submission.review.content.digest }) })
 assert.equal(agentResponse.status, 403)
 assert.match((await agentResponse.json()).error, /Agents cannot approve/)
 const unchanged = await h.get('/api/easel/state', reviewer)
 await approve(reviewer, 0)
 await approve(reviewer, 0, 409)
 assert.equal((await h.get('/api/easel/state', reviewer)).me.payDetail, unchanged.me.payDetail)
 assert.deepEqual((await h.get('/api/easel/state', reviewer)).me.capabilities, unchanged.me.capabilities)
 await h.command('revenue', { ...input, id: first.id, rate: '150' }, reviewer, 403)
 await approveBudget(403, reviewer)
 await h.command('pack-publish', { id: 'synthetic-easel-1' }, reviewer, 403)
 let reviewed = await sub()
 await h.command('revenue', { ...input, id: engineeringInput.id, department: eng.id, name: 'Engineering retainers', rate: '120' })
 assert.deepEqual((await sub()).review, reviewed.review, 'Engineering input changes keep Sales decisions')
 first = await h.command('revenue', { ...input, id: first.id, rate: '130' })
 assert.equal((await sub()).review.decisions.length, 0)
 assert.notEqual((await sub()).review.content.digest, reviewed.review.content.digest)
 assert.ok((await sub()).history.some(e => e.status === 'chain-restarted' && e.voidedDecisions.length === 1))
 await approve(reviewer, 0, 409, { pass: reviewed.review.pass, digest: reviewed.review.content.digest })
 await approve(reviewer, 0)
 await h.command('return-submission', { scenario: budget.id, department: sales.id, reason: 'Revise the rate' }, planner)
 assert.equal((await sub()).status, 'returned')
 await h.command('revenue', { ...input, id: first.id, rate: '140' }, submitter)
 await h.command('submit', { scenario: budget.id, department: sales.id }, submitter)
 assert.equal((await sub()).review.decisions.length, 0)
 assert.ok((await sub()).history.some(e => e.reason === 'Revise the rate' && e.voidedDecisions.length === 1))
 const v1 = (await sub()).review.version
 chain = await h.command('approval-chain-save', { ...chain, steps: [...chain.steps, { name: 'Final finance review', members: ['final@example.test'] }] })
 assert.equal((await sub()).review.version, v1)
 assert.equal((await row()).steps.length, 2)
 await approve(reviewer, 0)
 await h.command('approval-chain-restart', { scenario: budget.id, department: sales.id, pass: (await sub()).review.pass, version: chain.version, reason: 'Use the current policy' })
 assert.equal((await sub()).review.version, chain.version)
 assert.equal((await sub()).review.decisions.length, 0)
 assert.equal((await row()).steps.length, 3)
 // A completed reviewer can return; a later step cannot return early.
 await h.command('return-submission', { scenario: budget.id, department: sales.id, reason: 'Too early' }, finalReviewer, 403)
 await approve(reviewer, 0)
 await h.command('return-submission', { scenario: budget.id, department: sales.id, reason: 'Head recalls the review' }, reviewer)
 await h.command('submit', { scenario: budget.id, department: sales.id }, submitter)
 // Adding a position changes the exact content and requires live Pay detail.
 const payroll = await h.command('line', { name: 'Payroll', type: 'operating-expense', payroll: true })
 await h.command('position', { scenario: budget.id, department: sales.id, line: payroll.id, title: 'Sales hire', holder: 'Synthetic Easel person', start: '2026-01', annualSalary: '100000', dimensions: { [region.id]: east.id } })
 await approve(reviewer, 0, 403)
 assert.equal((await row()).steps[0].status, 'blocked')
 await h.command('pay-detail', { email: 'head@example.test', granted: true })
