 assert.equal(completed.review.decisions.length, 3)
 for (const decision of completed.review.decisions) { assert.equal(decision.content.digest, completed.review.content.digest); assert.ok(decision.by && decision.at && decision.chainVersion) }
 await h.command('return-submission', { scenario: budget.id, department: sales.id, reason: 'Frozen' }, h.owner, 409)
 const archive = await h.mf.dispatchFetch(h.origin + '/api/easel/export', { headers: { cookie: h.owner } })
 assert.equal(archive.status, 200)
 const zip = await JSZip.loadAsync(await archive.arrayBuffer())
 const files = Object.keys(zip.files)
 const allText = (await Promise.all(files.filter(n => /\.json$/.test(n)).map(n => zip.file(n).async('string')))).join('\n')
 assert.ok(allText.includes('approval-chain-version') && allText.includes(completed.review.content.digest))
 // Exercise the same public portability service and policy used by rer export/import.
