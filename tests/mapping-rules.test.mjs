import test from 'node:test'
import assert from 'node:assert/strict'
import { readWorkbook, evaluate } from './spreadsheet-proof.mjs'
import { harness } from './harness.mjs'

const file = (filename, rows) => ({
 filename,
 csv: `Date,Account,Type,Amount,Description\n${rows.join('\n')}\n`,
 columns: { date: 'Date', account: 'Account', accountType: 'Type', amount: 'Amount', description: 'Description' },
 dateFormat: 'YYYY-MM-DD', amountMode: 'debit-positive',
})
const account = (preview, code) => preview.accounts.find(row => row.account === code)
const month = (report, period) => report.months.find(row => row.period === period)

async function setup(h) {
 await h.command('workspace', { name: 'Harbour Services', currency: 'AUD', fiscalYearStart: 1, planStart: '2026-01' })
 const revenue = await h.command('line', { name: 'Services', type: 'revenue' })
 const costs = await h.command('line', { name: 'Software', type: 'operating-expense' })
 await h.command('department-map', { source: '', department: '' })
 const budget = (await h.get('/api/easel/state')).scenarios.find(s => s.kind === 'budget')
 return { revenue, costs, budget }
}

test('CONNECT-006 CONNECT-008 range rules map newly arriving accounts and only unresolved periods block dependent conclusions', async t => {
 const h = await harness(); t.after(() => h.close())
 const { revenue, budget } = await setup(h)
 const board = await h.person('board@example.test', 'viewer')
 const range = await h.command('account-rule', { match: 'range', from: '00400', to: '00499', target: revenue.id })
 const cash = await h.command('account-rule', { match: 'prefix', from: 'BANK-', target: 'cash' })
 const first = file('january.csv', [
  '2025-12-31,BANK-main,Bank,5000,Opening bank',
  '2026-01-10,00400,Income,-100,January service',
 ])
 const before = await h.get('/api/easel/state')
 const p1 = await h.kit('actuals', 'preview', first)
 assert.deepEqual(await h.get('/api/easel/state'), before, 'preview leaves the model and import history unchanged')
 assert.deepEqual((await h.get('/api/easel/actuals')).months, [], 'preview does not accept source rows')
 assert.equal(account(p1, '00400').target, revenue.id)
 assert.equal(account(p1, '00400').mappingStatus, 'mapped')
 assert.deepEqual(account(p1, '00400').ruleIds, [range.id])
 assert.deepEqual(account(p1, 'BANK-main').ruleIds, [cash.id])
 await h.kit('actuals', 'commit', { ...first, fingerprint: p1.fingerprint })
 const importedCash = await h.command('scenario-cash', { scenario: budget.id, basis: 'imported', receivables: '0', payables: '0', collectionLag: 0, paymentLag: 0 })
 assert.equal(importedCash.cash.openingCents, 500000)
 const current = await h.get(`/api/easel/scenario/${budget.id}`)
 const { forecast } = await h.command('approve-budget', { scenario: budget.id, revision: current.scenario.revision })
 await h.command('close-month', { scenario: forecast.id, month: '2026-01' })
 const january = await h.get('/api/easel/variance/2026-01')
 assert.equal(january.rows.find(row => row.line === revenue.id).actual, 10000)

 const second = file('february.csv', [
  '2026-02-12,00450,Income,-200,February service',
  '2026-02-13,900,Income,-30,Special service',
  '2026-02-14,ZERO,Other,10,Reclass debit',
  '2026-02-14,ZERO,Other,-10,Reclass credit',
 ])
 await h.command('account-rule', { match: 'prefix', from: 'ZERO', target: 'excluded' })
 const p2 = await h.kit('actuals', 'preview', second)
 assert.equal(account(p2, '00450').target, revenue.id, 'a previously unseen account inherits the numeric range')
 assert.deepEqual(account(p2, '00450').ruleIds, [range.id])
 assert.equal(account(p2, '900').mappingStatus, 'unmapped')
 assert.equal(p2.periods[0].blocked, true)
 assert.deepEqual(p2.periods[0].unmappedAccounts, ['900'])
 await h.kit('actuals', 'commit', { ...second, fingerprint: p2.fingerprint }, h.owner, 409)
 assert.deepEqual(await h.get('/api/easel/variance/2026-01'), january)
 const special = await h.command('account-rule', { match: 'prefix', from: '900', target: revenue.id })
 const ready = await h.kit('actuals', 'preview', second)
 assert.equal(ready.periods[0].blocked, false)
 await h.kit('actuals', 'commit', { ...second, fingerprint: ready.fingerprint })
 await h.command('account-rule-delete', { id: special.id })
 let reconciliation = await h.get('/api/easel/actuals')
 assert.equal(month(reconciliation, '2026-01').blocked, false)
 assert.equal(month(reconciliation, '2026-02').blocked, true)
 assert.deepEqual(month(reconciliation, '2026-02').unmappedAccounts, ['900'])
 assert.ok(reconciliation.unmapped.some(row => row.account === '900' && row.period === '2026-02'))
 await h.command('close-month', { scenario: forecast.id, month: '2026-02' }, h.owner, 409)
 await h.get(`/api/easel/scenario/${forecast.id}`)
 const replacement = await h.command('account-rule', { match: 'prefix', from: '900', target: revenue.id })
 await h.command('close-month', { scenario: forecast.id, month: '2026-02' })
 const february = await h.get('/api/easel/variance/2026-02')
 const service = february.rows.find(row => row.line === revenue.id)
 assert.equal(service.actual, 23000)
 assert.deepEqual(service.citations.map(row => row.account).sort(), ['00450', '900'], 'rule-mapped rows remain drillable evidence')
 const boardView = await h.get('/api/easel/variance/2026-02', board)
 const boardService = boardView.rows.find(row => row.line === revenue.id)
 assert.equal(boardService.actual, service.actual)
 assert.deepEqual(boardService.citations, [], 'CONNECT-008 viewer reads amounts without source rows')
 assert.doesNotMatch(JSON.stringify(boardView), /Special service|February service/)
 const live = await h.get(`/api/easel/scenario/${forecast.id}`)
 const kept = await h.command('reforecast-save', { from: forecast.id, revision: live.scenario.revision, name: 'February kept forecast' })
 const frozen = await h.get(`/api/easel/scenario/${kept.id}`)
 const snapshot = await h.get(`/api/easel/snapshot/${kept.reforecast.snapshot}`)
 await h.command('account-rule-delete', { id: replacement.id })
 await h.get(`/api/easel/scenario/${forecast.id}`, h.owner, 409)
 await h.get('/api/easel/variance/2026-02', h.owner, 409)
 const unaffected = (await h.get('/api/easel/variance/2026-01')).rows.find(row => row.line === revenue.id)
 assert.equal(unaffected.actual, 10000)
 assert.deepEqual(unaffected.citations, january.rows.find(row => row.line === revenue.id).citations)
 assert.deepEqual(await h.get(`/api/easel/scenario/${kept.id}`), frozen)
 assert.deepEqual(await h.get(`/api/easel/snapshot/${kept.reforecast.snapshot}`), snapshot)
 await h.command('account-map', { account: '900', target: revenue.id })
 const restored = (await h.get('/api/easel/variance/2026-02')).rows.find(row => row.line === revenue.id)
 assert.equal(restored.actual, service.actual)
 assert.equal(restored.variance, service.variance)
 assert.deepEqual(restored.citations, service.citations)
 assert.deepEqual((await h.get(`/api/easel/scenario/${forecast.id}`)).calculation, live.calculation)
 reconciliation = await h.get('/api/easel/actuals')
 assert.equal(month(reconciliation, '2026-02').blocked, false)
 const zeroRule = (await h.get('/api/easel/state')).accountRules.find(r => r.from === 'ZERO')
 await h.command('account-rule-delete', { id: zeroRule.id })
 reconciliation = await h.get('/api/easel/actuals')
 assert.equal(month(reconciliation, '2026-02').unmapped, 0)
 assert.equal(month(reconciliation, '2026-02').blocked, true, 'unmapped zero-net accounts still block')
 assert.equal(month(reconciliation, '2026-02').revenue, null, 'incomplete revenue is not reported as final')
 await h.get('/api/easel/variance/2026-02', h.owner, 409)
 const excel = await h.mf.dispatchFetch(h.origin + '/api/easel/actuals.xlsx', { headers: { cookie: h.owner } })
 const workbook = await readWorkbook(await excel.arrayBuffer())
 assert.match(JSON.stringify(workbook.getWorksheet('Reconciliation').getSheetValues()), /Blocked: ZERO/)
 assert.match(JSON.stringify(workbook.getWorksheet('Unmapped accounts').getSheetValues()), /ZERO/)
})

test('CONNECT-006 exact overrides, agreeing rules, ambiguity and reviewed rule changes remain explicit', async t => {
 const h = await harness(); t.after(() => h.close())
 const { revenue, costs } = await setup(h)
 const contributor = await h.person('planner@example.test', 'contributor', [(await h.command('department', { name: 'Delivery' })).id])
 await h.command('account-rule', { match: 'prefix', from: 'PRIVATE', target: revenue.id }, contributor, 403)
 assert.deepEqual((await h.get('/api/easel/state', contributor)).accountRules, [])
 await h.command('account-rule', { match: 'range', from: 'A1', to: 'A9', target: revenue.id }, h.owner, 400)
 await h.command('account-rule', { match: 'range', from: '500', to: '400', target: revenue.id }, h.owner, 400)
 const prefix = await h.command('account-rule', { match: 'prefix', from: ' SUB- ', target: revenue.id })
 const type = await h.command('account-rule', { match: 'type', from: ' Income ', target: revenue.id })
 const source = file('subscriptions.csv', [
  '2026-01-01,SUB-main,Income,-100,Subscriptions',
  '2026-01-02,OTHER,Income,-20,Other income',
  '2026-01-03,sub-small,income,-5,Unclassified receipt',
 ])
 let preview = await h.kit('actuals', 'preview', source)
 assert.equal(account(preview, 'SUB-main').mappingStatus, 'mapped')
 assert.deepEqual(account(preview, 'SUB-main').ruleIds.sort(), [prefix.id, type.id].sort())
 assert.deepEqual(account(preview, 'OTHER').ruleIds, [type.id])
 assert.equal(account(preview, 'sub-small').mappingStatus, 'unmapped', 'prefixes and provider types are case sensitive')
 await h.command('account-map', { account: 'sub-small', target: 'excluded' })
 const conflict = await h.command('account-rule', { match: 'prefix', from: 'SUB-', target: costs.id })
 preview = await h.kit('actuals', 'preview', source)
 assert.equal(account(preview, 'SUB-main').mappingStatus, 'ambiguous')
 assert.equal(account(preview, 'SUB-main').target, null)
 assert.deepEqual(new Set(account(preview, 'SUB-main').ruleIds), new Set([prefix.id, type.id, conflict.id]))
 assert.equal(preview.periods[0].blocked, true)
 await h.kit('actuals', 'commit', { ...source, fingerprint: preview.fingerprint }, h.owner, 409)
 await h.command('account-map', { account: 'SUB-main', target: revenue.id })
 const reviewed = await h.kit('actuals', 'preview', source)
 assert.equal(account(reviewed, 'SUB-main').mappingStatus, 'mapped')
 assert.equal(account(reviewed, 'SUB-main').target, revenue.id)
 assert.equal(reviewed.periods[0].blocked, false)
 await h.command('account-rule', { id: type.id, match: 'type', from: 'Income', target: costs.id })
 await h.kit('actuals', 'commit', { ...source, fingerprint: reviewed.fingerprint }, h.owner, 409)
 const refreshed = await h.kit('actuals', 'preview', source)
 assert.equal(account(refreshed, 'OTHER').target, costs.id)
 assert.equal(account(refreshed, 'SUB-main').target, revenue.id)
 await h.kit('actuals', 'commit', { ...source, fingerprint: refreshed.fingerprint })
 const reconciliation = await h.get('/api/easel/actuals')
 assert.equal(month(reconciliation, '2026-01').blocked, false)
 assert.equal(month(reconciliation, '2026-01').revenue, 10000)
 assert.equal(month(reconciliation, '2026-01').costs, -2000)
})

test('CONNECT-007 accepts attributed balance-sheet journals with reusable targets and a true zero-sum trial balance', async t => {
 const { balanceSource, seedBalanceActuals } = await import('./balance-actuals-fixture.mjs')
 const h = await harness(); t.after(() => h.close())
 const { revenue, expense, receivables } = await seedBalanceActuals(h.command)
 const board = await h.person('board@example.test', 'viewer')
 const before = await h.get('/api/easel/actuals')
 const preview = await h.kit('actuals', 'preview', balanceSource)
 assert.deepEqual(await h.get('/api/easel/actuals'), before, 'balance preview accepts no rows')
 assert.equal(account(preview, '1101').target, 'bs:receivables')
 assert.deepEqual(account(preview, '1101').ruleIds, [receivables.id], 'new in-range balance account is automatically listed')
 await h.kit('actuals', 'commit', { ...balanceSource, fingerprint: preview.fingerprint })
 let report = await h.get('/api/easel/actuals')
 const january = report.trialBalances.find(t => t.period === '2026-01')
 assert.equal(january.debit, 14240000)
 assert.equal(january.credit, 14240000)
 assert.equal(january.difference, 0)
 assert.equal(january.balanced, true)
 assert.deepEqual(Object.fromEntries(january.balances.map(b => [b.target, b.amount])), {
  cash: 9600000, 'bs:receivables': 2200000, 'bs:prepaid': 240000, 'bs:fixed-assets': 1800000,
  'bs:payables': 800000, 'bs:accrued-liabilities': 300000, 'bs:deferred-revenue': 600000,
  'bs:debt': 2000000, 'bs:equity': 9540000,
 })
 const source = january.balances.find(b => b.target === 'bs:receivables').sources.find(s => s.account === '1101')
 assert.equal(source.rows, 1); assert.equal(source.accountType, 'Receivable')
 assert.deepEqual(source.periods, ['2026-01']); assert.equal(source.batches[0], preview.destination)
 assert.equal(month(report, '2026-01').balanced, true, 'classification includes balance-sheet lines')
 assert.equal(month(report, '2026-01').balanceSheet, 1000000)
 assert.equal(month(report, '2026-01').revenue, 1000000)
 assert.equal(month(report, '2026-01').costs, 400000)
 await h.get('/api/easel/actuals', board, 403)
 await h.command('account-map', { account: 'PRIVATE', target: 'bs:equity' }, board, 403)
 await h.command('account-rule', { match: 'prefix', from: 'PRIVATE', target: 'bs:debt' }, board, 403)
 const budget = (await h.get('/api/easel/state')).scenarios.find(s => s.kind === 'budget')
 const { forecast } = await h.command('approve-budget', { scenario: budget.id, revision: budget.revision })
 await h.command('close-month', { scenario: forecast.id, month: '2026-01' })
 const variance = await h.get('/api/easel/variance/2026-01')
 assert.equal(variance.rows.find(r => r.line === revenue.id).actual, 1000000)
 assert.equal(variance.rows.find(r => r.line === expense.id).actual, 400000, 'balance-sheet movements do not become P&L')
 const response = await h.mf.dispatchFetch(h.origin + '/api/easel/actuals.xlsx', { headers: { cookie: h.owner } })
 const workbook = await readWorkbook(await response.arrayBuffer())
 const trial = workbook.getWorksheet('Trial balance')
 assert.equal(trial.getCell('D4').value.formula, 'B4-C4')
 assert.equal(evaluate(trial, 'D4'), 0)
 assert.equal(workbook.getWorksheet('Balance-sheet actuals').getCell('C13').value, 2200000)
 assert.match(JSON.stringify(workbook.getWorksheet('Ledger balances').getSheetValues()), /1101/)
 await h.command('account-rule-delete', { id: receivables.id })
 report = await h.get('/api/easel/actuals')
 assert.equal(report.trialBalances[1].blocked, true)
 assert.equal(report.trialBalances[1].balanced, false)
 assert.ok(report.trialBalances[1].balances.every(b => b.amount === null), 'incomplete balances are unavailable, never zero')
 await h.command('close-month', { scenario: forecast.id, month: '2026-02' }, h.owner, 409)
 await h.command('account-rule', { match: 'range', from: '1100', to: '1199', target: 'bs:receivables' })
 const correction = file('february-imbalance.csv', ['2026-02-01,1000,Bank,0.01,Unbalanced source journal'])
 const cp = await h.kit('actuals', 'preview', correction)
 const imported = await h.kit('actuals', 'commit', { ...correction, fingerprint: cp.fingerprint })
 report = await h.get('/api/easel/actuals')
 assert.equal(report.trialBalances[2].difference, 1)
 assert.equal(report.trialBalances[2].balanced, false, 'classification completeness does not mean debit/credit equality')
 assert.equal(report.months[2].balanced, true)
 assert.deepEqual(report.trialBalances[1], january, 'later source imbalance preserves earlier trial balances')
 await h.kit('actuals', 'undo', { id: imported.batch.id })
 report = await h.get('/api/easel/actuals')
 assert.equal(report.trialBalances.length, 2)
 assert.deepEqual(report.trialBalances[1], january)
})
