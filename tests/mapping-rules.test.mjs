 const contributor = await h.person('planner@example.test', 'contributor', [(await h.command('department', { name: 'Delivery' })).id])
 await h.command('account-rule', { match: 'prefix', from: 'PRIVATE', target: revenue.id }, contributor, 403)
 assert.deepEqual((await h.get('/api/easel/state', contributor)).accountRules, [])
 await h.command('account-rule', { match: 'range', from: 'A1', to: 'A9', target: revenue.id }, h.owner, 400)
