const file = (filename, rows) => ({
 filename,
 csv: `Date,Account,Type,Amount,Description\n${rows.join('\n')}\n`,
 columns: { date: 'Date', account: 'Account', accountType: 'Type', amount: 'Amount', description: 'Description' },
 dateFormat: 'YYYY-MM-DD', amountMode: 'debit-positive',
})
const account = (preview, code) => preview.accounts.find(row => row.account === code)
const month = (report, period) => report.months.find(row => row.period === period)

async function setup(h) {
 await h.command('workspace', { name: 'Harbour Services', currency: 'AUD', fiscalYearStart: 1, planStart: '2026-01' })
 const revenue = await h.command('line', { name: 'Services', type: 'revenue' })
 const costs = await h.command('line', { name: 'Software', type: 'operating-expense' })
 await h.command('department-map', { source: '', department: '' })
 const budget = (await h.get('/api/easel/state')).scenarios.find(s => s.kind === 'budget')
 return { revenue, costs, budget }
}

